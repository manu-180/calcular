import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { KG_POR_LB, M_POR_PULGADA } from "../definicion";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const m = 69 * M_POR_PULGADA;
  const ejemplo = imperial
    ? [
        `Лице со тежина од 160 фунти и висина од 5 стапки и 9 инчи има БМИ ${n((160 * KG_POR_LB) / (m * m))}, односно нормална тежина.`,
        `За оваа висина здравата тежина е од ${n((18.5 * m * m) / KG_POR_LB)} до ${n((24.9 * m * m) / KG_POR_LB)} фунти.`,
      ]
    : [
        `Лице со тежина од 70 кг и висина од ${n(1.75, 2)} м има БМИ ${n(70 / (1.75 * 1.75))}, односно нормална тежина.`,
        `За оваа висина здравата тежина е од ${n(18.5 * 1.75 * 1.75)} до ${n(24.9 * 1.75 * 1.75)} кг.`,
      ];
  return {
    h1: "Калкулатор за индекс на телесна маса (БМИ)",
    title: tituloQueEntre(`Индекс на телесна маса (БМИ): ${ctx.nombrePais}`, "Индекс на телесна маса: калкулатор", "Калкулатор за БМИ"),
    description: "Пресметајте го индексот на телесна маса според тежина и висина и видете ја категоријата според СЗО и здравата тежина.",
    intro: [
      "Внесете ја тежината и висината. Ќе го видите вашиот БМИ, неговата категорија според Светската здравствена организација и здравиот опсег на тежина за вашата висина.",
      "Ова е општ ориентир за возрасни. Не ја заменува консултацијата со медицински специјалист.",
    ],
    comoSeCalcula: [
      imperial ? "БМИ = тежина во фунти × 703 ÷ (висина во инчи × висина во инчи)." : "БМИ = тежина во килограми ÷ (висина во метри × висина во метри).",
      `Под ${n(18.5)} е намалена тежина. Од ${n(18.5)} до ${n(24.9)} е нормална тежина. Од 25 до ${n(29.9)} е прекумерна тежина. Од 30 нагоре е дебелина.`,
      `Здравата тежина за вашата висина дава БМИ меѓу ${n(18.5)} и ${n(24.9)}.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Кој БМИ е нормален?",
        respuesta: `Според СЗО, кај возрасните тоа е БМИ меѓу ${n(18.5)} и ${n(24.9)}. Границите се исти за жени и мажи.`,
      },
      {
        pregunta: "Дали БМИ е соодветен за секого?",
        respuesta: "Не. Не разликува мускули од маснотии, затоа кај многу мускулести лица може да излезе висок. При бременост, кај деца и кај адолесценти се користи на поинаков начин.",
      },
      {
        pregunta: "Како се пресметува БМИ рачно?",
        respuesta: `Поделете ја тежината во килограми со висината во метри на квадрат. За 70 кг и ${n(1.75, 2)} м тоа е 70 ÷ (${n(1.75, 2)} × ${n(1.75, 2)}) = ${n(70 / (1.75 * 1.75))}.`,
      },
    ],
    glosario: [
      { termino: "БМИ", definicion: "Индекс на телесна маса: покажува каков е односот меѓу тежината и висината." },
      { termino: "СЗО", definicion: "Светската здравствена организација. Таа ги одредува категориите на БМИ за возрасни." },
    ],
  };
};
