import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { KG_POR_LB, M_POR_PULGADA } from "../definicion";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const m = 69 * M_POR_PULGADA;
  const ejemplo = imperial
    ? [
        `Човек с тегло 160 фунта и ръст 5 фута и 9 инча има ИТМ ${n((160 * KG_POR_LB) / (m * m))}, тоест нормално тегло.`,
        `При този ръст здравословното тегло е от ${n((18.5 * m * m) / KG_POR_LB)} до ${n((24.9 * m * m) / KG_POR_LB)} фунта.`,
      ]
    : [
        `Човек с тегло 70 кг и ръст ${n(1.75, 2)} м има ИТМ ${n(70 / (1.75 * 1.75))}, тоест нормално тегло.`,
        `При този ръст здравословното тегло е от ${n(18.5 * 1.75 * 1.75)} до ${n(24.9 * 1.75 * 1.75)} кг.`,
      ];
  return {
    h1: "Калкулатор за индекс на телесната маса (ИТМ)",
    title: tituloQueEntre(`Индекс на телесната маса (ИТМ): ${ctx.nombrePais}`, "Индекс на телесната маса: калкулатор", "Калкулатор за ИТМ"),
    description: "Изчислете индекса на телесната си маса по тегло и ръст, вижте категорията според СЗО и здравословното тегло за Вашия ръст.",
    intro: [
      "Въведете теглото и ръста си. Ще видите своя ИТМ, категорията му според Световната здравна организация и здравословния диапазон на теглото за Вашия ръст.",
      "Това е общ ориентир за възрастни. Той не замества консултацията с медицински специалист.",
    ],
    comoSeCalcula: [
      imperial ? "ИТМ = тегло във фунтове × 703 ÷ (ръст в инчове × ръст в инчове)." : "ИТМ = тегло в килограми ÷ (ръст в метри × ръст в метри).",
      `Под ${n(18.5)} е поднормено тегло. От ${n(18.5)} до ${n(24.9)} е нормално тегло. От 25 до ${n(29.9)} е наднормено тегло. От 30 нагоре е затлъстяване.`,
      `Здравословното тегло е това, при което ИТМ за Вашия ръст е между ${n(18.5)} и ${n(24.9)}.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Какъв ИТМ е нормален?",
        respuesta: `Според СЗО при възрастните това е ИТМ между ${n(18.5)} и ${n(24.9)}. Границите са едни и същи за жени и мъже.`,
      },
      {
        pregunta: "Подходящ ли е ИТМ за всеки?",
        respuesta: "Не. Той не различава мускули от мазнини, затова при много мускулести хора може да излезе висок. При бременност, деца и юноши се използва по различен начин.",
      },
      {
        pregunta: "Как се изчислява ИТМ ръчно?",
        respuesta: `Разделете теглото в килограми на ръста в метри, повдигнат на квадрат. При 70 кг и ${n(1.75, 2)} м това е 70 ÷ (${n(1.75, 2)} × ${n(1.75, 2)}) = ${n(70 / (1.75 * 1.75))}.`,
      },
    ],
    glosario: [
      { termino: "ИТМ", definicion: "Индекс на телесната маса: показва как се отнася теглото към ръста." },
      { termino: "СЗО", definicion: "Световната здравна организация, която определя категориите на ИТМ за възрастни." },
    ],
  };
};
