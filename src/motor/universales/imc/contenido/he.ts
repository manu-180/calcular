import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { GRAMATICA } from "../../../i18n/gramatica";
import { KG_POR_LB, M_POR_PULGADA } from "../definicion";

export const contenidoHe: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const m = 69 * M_POR_PULGADA;
  const en = GRAMATICA.he.en(ctx.nombrePais);
  const ejemplo = imperial
    ? [
        `מי ששוקל 160 ליברות וגובהו 5 רגל ו-9 אינץ' מקבל BMI של ${n((160 * KG_POR_LB) / (m * m))}: משקל תקין.`,
        `בגובה הזה משקל תקין הוא בין ${n((18.5 * m * m) / KG_POR_LB)} ל-${n((24.9 * m * m) / KG_POR_LB)} ליברות.`,
      ]
    : [
        `מי ששוקל 70 ק"ג וגובהו ${n(1.75, 2)} מטר מקבל BMI של ${n(70 / (1.75 * 1.75))}: משקל תקין.`,
        `בגובה הזה משקל תקין הוא בין ${n(18.5 * 1.75 * 1.75)} ל-${n(24.9 * 1.75 * 1.75)} ק"ג.`,
      ];
  return {
    h1: "מחשבון BMI",
    title: tituloQueEntre(`מחשבון BMI ${en}: מדד מסת גוף`, `מחשבון BMI ${en}`, "מחשבון BMI: מדד מסת גוף"),
    description: "חשבו את מדד מסת הגוף (BMI) לפי משקל וגובה, ראו את הקטגוריה לפי ארגון הבריאות העולמי ואת טווח המשקל התקין לגובה שלכם.",
    intro: [
      "הזינו משקל וגובה. תקבלו את ה-BMI, את הקטגוריה שלו לפי ארגון הבריאות העולמי ואת טווח המשקל התקין לגובה שלכם.",
      "זה מדד כללי למבוגרים, והוא לא מחליף ייעוץ של איש מקצוע בתחום הבריאות.",
    ],
    comoSeCalcula: [
      imperial ? "BMI = משקל בליברות × 703 ÷ (גובה באינצ'ים × גובה באינצ'ים)." : 'BMI = משקל בק"ג ÷ (גובה במטרים × גובה במטרים).',
      `מתחת ל-${n(18.5)} זה תת משקל. בין ${n(18.5)} ל-${n(24.9)} זה משקל תקין. בין 25 ל-${n(29.9)} זה עודף משקל. מ-30 ומעלה זו השמנה.`,
      `טווח המשקל התקין הוא זה שנותן BMI בין ${n(18.5)} ל-${n(24.9)} בגובה שלכם.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "מה נחשב BMI תקין?",
        respuesta: `לפי ארגון הבריאות העולמי, BMI בין ${n(18.5)} ל-${n(24.9)} אצל מבוגרים. הטווח זהה לנשים ולגברים.`,
      },
      {
        pregunta: "האם BMI מתאים לכולם?",
        respuesta: "לא. הוא לא מבחין בין שריר לשומן, ולכן אצל אנשים שריריים מאוד הוא עלול לצאת גבוה. בהריון ואצל ילדים ובני נוער משתמשים בו אחרת.",
      },
      {
        pregunta: "איך מחשבים BMI?",
        respuesta: imperial
          ? "מכפילים את המשקל בליברות ב-703 ומחלקים בגובה באינצ'ים בריבוע. בגובה 5 רגל ו-9 אינץ' זה 69 × 69."
          : `מחלקים את המשקל בק"ג בגובה במטרים בריבוע. בגובה ${n(1.75, 2)} מטר זה ${n(1.75, 2)} × ${n(1.75, 2)}.`,
      },
    ],
    glosario: [
      { termino: "BMI", definicion: "מדד מסת גוף: היחס בין המשקל לגובה." },
      { termino: "ארגון הבריאות העולמי", definicion: "הארגון שקבע את קטגוריות ה-BMI למבוגרים (WHO)." },
    ],
  };
};
