import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { KG_POR_LB, M_POR_PULGADA } from "../definicion";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const m = 69 * M_POR_PULGADA;
  const ejemplo = imperial
    ? [
        `При весе 160 фунтов и росте 5 футов 9 дюймов ИМТ равен ${n((160 * KG_POR_LB) / (m * m))}. Это нормальный вес.`,
        `При таком росте нормальный вес составляет от ${n((18.5 * m * m) / KG_POR_LB)} до ${n((24.9 * m * m) / KG_POR_LB)} фунтов.`,
      ]
    : [
        `При весе 70 кг и росте ${n(1.75, 2)} м ИМТ равен ${n(70 / (1.75 * 1.75))}. Это нормальный вес.`,
        `При таком росте нормальный вес составляет от ${n(18.5 * 1.75 * 1.75)} до ${n(24.9 * 1.75 * 1.75)} кг.`,
      ];
  return {
    h1: "Калькулятор индекса массы тела (ИМТ)",
    title: tituloQueEntre(`Калькулятор ИМТ: ${ctx.nombrePais}`, "Калькулятор индекса массы тела", "Калькулятор ИМТ"),
    description: "Рассчитайте индекс массы тела по весу и росту, узнайте свою категорию по шкале ВОЗ и нормальный вес для вашего роста.",
    intro: [
      "Введите вес и рост. Калькулятор покажет ваш ИМТ, категорию по классификации Всемирной организации здравоохранения и диапазон нормального веса для вашего роста.",
      "Это общий ориентир для взрослых. Результат не заменяет консультацию врача.",
    ],
    comoSeCalcula: [
      imperial ? "ИМТ = вес в фунтах × 703 ÷ (рост в дюймах × рост в дюймах)." : "ИМТ = вес в килограммах ÷ (рост в метрах × рост в метрах).",
      `Меньше ${n(18.5)} означает недостаточный вес. От ${n(18.5)} до ${n(24.9)} считается нормой. От 25 до ${n(29.9)} означает избыточный вес. 30 и выше относится к ожирению.`,
      `Нормальный вес для вашего роста дает ИМТ от ${n(18.5)} до ${n(24.9)}.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Какой ИМТ считается нормальным?",
        respuesta: `По данным ВОЗ, у взрослых нормой считается ИМТ от ${n(18.5)} до ${n(24.9)}. Диапазон одинаков для женщин и мужчин.`,
      },
      {
        pregunta: "Подходит ли ИМТ всем?",
        respuesta: "Нет. Индекс не отличает мышцы от жира, поэтому у спортсменов он бывает завышен. Для беременных, детей и подростков его оценивают по другим правилам.",
      },
      {
        pregunta: "Как рассчитать ИМТ самостоятельно?",
        respuesta: imperial
          ? "Умножьте вес в фунтах на 703 и разделите на квадрат роста в дюймах. При росте 5 футов 9 дюймов это 69 × 69."
          : `Разделите вес в килограммах на квадрат роста в метрах. При росте ${n(1.75, 2)} м это ${n(1.75, 2)} × ${n(1.75, 2)}.`,
      },
      {
        pregunta: "Что делать, если ИМТ вне нормы?",
        respuesta: "ИМТ показывает только соотношение веса и роста. Чтобы понять, есть ли повод для беспокойства, обратитесь к врачу.",
      },
    ],
    glosario: [
      { termino: "ИМТ", definicion: "Индекс массы тела: соотношение веса и роста." },
      { termino: "ВОЗ", definicion: "Всемирная организация здравоохранения, которая задает категории ИМТ для взрослых." },
    ],
  };
};
