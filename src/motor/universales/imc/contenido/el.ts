import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { KG_POR_LB, M_POR_PULGADA } from "../definicion";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const m = 69 * M_POR_PULGADA;
  const ejemplo = imperial
    ? [
        `Ένα άτομο με βάρος 160 lb και ύψος 5 ft 9 in έχει ΔΜΣ ${n((160 * KG_POR_LB) / (m * m))}. Αυτό είναι φυσιολογικό βάρος.`,
        `Το υγιές βάρος για αυτό το ύψος είναι από ${n((18.5 * m * m) / KG_POR_LB)} lb έως ${n((24.9 * m * m) / KG_POR_LB)} lb.`,
      ]
    : [
        `Ένα άτομο με βάρος 70 kg και ύψος ${n(1.75, 2)} m έχει ΔΜΣ ${n(70 / (1.75 * 1.75))}. Αυτό είναι φυσιολογικό βάρος.`,
        `Το υγιές βάρος για αυτό το ύψος είναι από ${n(18.5 * 1.75 * 1.75)} kg έως ${n(24.9 * 1.75 * 1.75)} kg.`,
      ];
  return {
    h1: "Υπολογισμός δείκτη μάζας σώματος (ΔΜΣ)",
    title: tituloQueEntre(`Δείκτης μάζας σώματος (BMI): ${ctx.nombrePais}`, "Υπολογισμός δείκτη μάζας σώματος (BMI)", "Δείκτης μάζας σώματος"),
    description: "Υπολογίστε τον δείκτη μάζας σώματος (ΔΜΣ ή BMI) από το βάρος και το ύψος. Δείτε την κατηγορία σας κατά τον ΠΟΥ και το υγιές βάρος για το ύψος σας.",
    intro: [
      "Εισάγετε βάρος και ύψος. Θα δείτε τον ΔΜΣ σας, την κατηγορία κατά την ταξινόμηση του Παγκόσμιου Οργανισμού Υγείας και το εύρος υγιούς βάρους για το ύψος σας.",
      "Πρόκειται για γενικό δείκτη για ενηλίκους. Δεν αντικαθιστά τη συμβουλή γιατρού.",
    ],
    comoSeCalcula: [
      imperial ? "ΔΜΣ = βάρος σε λίβρες × 703 ÷ (ύψος σε ίντσες × ύψος σε ίντσες)." : "ΔΜΣ = βάρος σε κιλά ÷ (ύψος σε μέτρα × ύψος σε μέτρα).",
      `Κάτω από ${n(18.5)} σημαίνει χαμηλό βάρος, από ${n(18.5)} έως ${n(24.9)} φυσιολογικό βάρος και από 25 έως ${n(29.9)} υπέρβαρο. Από 30 και πάνω πρόκειται για παχυσαρκία.`,
      `Το υγιές βάρος περιλαμβάνει τις τιμές στις οποίες ο ΔΜΣ για το ύψος σας μένει ανάμεσα σε ${n(18.5)} και ${n(24.9)}.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Ποιος ΔΜΣ θεωρείται φυσιολογικός;",
        respuesta: `Κατά τον ΠΟΥ, για ενηλίκους από ${n(18.5)} έως ${n(24.9)}. Τα όρια είναι ίδια για γυναίκες και άνδρες.`,
      },
      {
        pregunta: "Ταιριάζει ο ΔΜΣ σε όλους;",
        respuesta: "Όχι. Δεν ξεχωρίζει τους μύες από το λίπος, οπότε σε άτομα με πολλή μυϊκή μάζα μπορεί να βγαίνει υψηλότερος. Σε εγκύους, παιδιά και εφήβους αξιολογείται διαφορετικά.",
      },
      {
        pregunta: "Τι κάνω αν ο ΔΜΣ μου είναι υψηλός;",
        respuesta: "Συζητήστε το αποτέλεσμα με γιατρό ή διαιτολόγο. Αξίζει να το δείτε μαζί με άλλους δείκτες: την περίμετρο μέσης, τη διατροφή και τη σωματική δραστηριότητα.",
      },
    ],
    glosario: [
      { termino: "ΔΜΣ (BMI)", definicion: "Δείκτης μάζας σώματος: η σχέση του βάρους σας με το τετράγωνο του ύψους." },
      { termino: "ΠΟΥ", definicion: "Παγκόσμιος Οργανισμός Υγείας. Ορίζει τις κατηγορίες ΔΜΣ για ενηλίκους." },
    ],
  };
};
