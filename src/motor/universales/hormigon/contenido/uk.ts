import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MEZCLA } from "../definicion";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const ft3 = 10 * 10 * (4 / 12);
        return [
          `Для подвірʼя 10 × 10 ft завтовшки 4 in потрібно ${n(ft3)} ft³ бетону, тобто ${n(ft3 / 27)} кубічного ярда.`,
          `За прикладом суміші на це піде приблизно ${n((MEZCLA.cementoKg * ft3 * 0.0283168466) / 0.45359237, 0)} lb цементу.`,
        ];
      })()
    : (() => {
        const volumen = 4 * 3 * 0.1;
        return [
          `Для бетонної плити 4 × 3 м завтовшки 10 см потрібно ${n(volumen, 1)} м³ бетону.`,
          `За прикладом суміші на це піде приблизно ${n(MEZCLA.cementoKg * volumen, 0)} кг цементу, ${n(MEZCLA.arenaM3 * volumen)} м³ піску і ${n(MEZCLA.piedraM3 * volumen)} м³ щебеню.`,
        ];
      })();
  return {
    h1: "Калькулятор бетону",
    title: tituloQueEntre(`Калькулятор бетону: ${ctx.nombrePais}`, "Калькулятор бетону і цементу", "Калькулятор бетону"),
    description: `Розрахуйте, скільки бетону потрібно на плиту, у ${imperial ? "кубічних ярдах" : "кубічних метрах"}, і приблизно скільки цементу, піску і щебеню купити.`,
    intro: [
      "Введіть довжину, ширину і товщину. Ви побачите обʼєм бетону і приблизну кількість матеріалів для суміші.",
      "Кількість матеріалів залежить від пропорцій суміші. Для прикладу калькулятор бере звичайну суміш 1:2:3.",
    ],
    comoSeCalcula: [
      imperial
        ? "Обʼєм = довжина × ширина × товщина, з товщиною у футах. Кубічні фути ділять на 27, щоб отримати кубічні ярди."
        : "Обʼєм = довжина × ширина × товщина, з товщиною в метрах.",
      "До обʼєму додається запас на нерівну основу і втрати бетону.",
      `На 1 м³ приблизно ${MEZCLA.cementoKg} кг цементу, ${n(MEZCLA.arenaM3)} м³ піску, ${n(MEZCLA.piedraM3, 1)} м³ щебеню і ${MEZCLA.aguaL} літрів води.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Скільки цементу потрібно на 1 м³ бетону?",
        respuesta: `Для суміші 1:2:3 близько ${MEZCLA.cementoKg} кг. Для міцнішого бетону цементу потрібно більше.`,
      },
      {
        pregunta: "Скільки кубічних футів у кубічному ярді?",
        respuesta: "27. Кубічний ярд дорівнює кубу 3 ft × 3 ft × 3 ft.",
      },
      {
        pregunta: "Чи варто замовити готовий бетон?",
        respuesta: "Для великих заливок готовий бетон зазвичай однорідніший і швидший, його продають кубометрами. Для невеликих робіт поширено замішувати бетон на місці в цих пропорціях.",
      },
    ],
    glosario: [
      { termino: "Пропорції суміші", definicion: "Співвідношення цементу, піску, щебеню і води в суміші." },
      { termino: "Кубічний метр (м³)", definicion: "Обʼєм куба зі стороною 1 метр." },
    ],
  };
};
