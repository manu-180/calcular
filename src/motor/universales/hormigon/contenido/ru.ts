import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MEZCLA } from "../definicion";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const ft3 = 10 * 10 * (4 / 12);
        return [
          `Для площадки 10 × 10 футов толщиной 4 дюйма нужно ${n(ft3)} куб. фута бетона, то есть ${n(ft3 / 27)} куб. ярда.`,
          `По базовой пропорции это около ${n((MEZCLA.cementoKg * ft3 * 0.0283168466) / 0.45359237, 0)} фунтов цемента.`,
        ];
      })()
    : (() => {
        const volumen = 4 * 3 * 0.1;
        return [
          `Для плиты 4 × 3 м толщиной 10 см нужно ${n(volumen, 1)} м³ бетона.`,
          `По базовой пропорции это около ${n(MEZCLA.cementoKg * volumen, 0)} кг цемента, ${n(MEZCLA.arenaM3 * volumen)} м³ песка и ${n(MEZCLA.piedraM3 * volumen)} м³ щебня.`,
        ];
      })();
  return {
    h1: "Калькулятор бетона",
    title: tituloQueEntre(`Калькулятор бетона: ${ctx.nombrePais}`, "Калькулятор бетона и цемента", "Калькулятор бетона"),
    description: `Рассчитайте, сколько бетона нужно на плиту, в ${imperial ? "кубических ярдах" : "кубических метрах"}, и примерно сколько купить цемента, песка и щебня.`,
    intro: [
      "Введите длину, ширину и толщину. Калькулятор покажет объем бетона и примерное количество материалов для замеса.",
      "Количество материалов зависит от марки бетона. Здесь за основу взята смесь общего назначения 1:2:3.",
    ],
    comoSeCalcula: [
      imperial
        ? "Объем = длина × ширина × толщина, где толщина в футах. Чтобы получить кубические ярды, кубические футы делят на 27."
        : "Объем = длина × ширина × толщина, где толщина в метрах.",
      "К объему добавляется запас на неровности основания и потери.",
      `На 1 м³: около ${MEZCLA.cementoKg} кг цемента, ${n(MEZCLA.arenaM3)} м³ песка, ${n(MEZCLA.piedraM3, 1)} м³ щебня и ${MEZCLA.aguaL} литров воды.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Сколько цемента нужно на 1 куб бетона?",
        respuesta: `При пропорции 1:2:3 около ${MEZCLA.cementoKg} кг. Для более прочного бетона цемента нужно больше.`,
      },
      {
        pregunta: "Как рассчитать объем бетона для плиты?",
        respuesta: `Перемножьте длину, ширину и толщину в метрах. Плита 4 × 3 м толщиной 10 см требует ${n(1.2, 1)} м³ бетона.`,
      },
      {
        pregunta: "Лучше заказать готовый бетон?",
        respuesta: "Для больших объемов готовый бетон обычно однороднее и быстрее в работе. Для небольших работ бетон часто замешивают на месте по этим пропорциям.",
      },
    ],
    glosario: [
      { termino: "Пропорция смеси", definicion: "Соотношение цемента, песка, щебня и воды в замесе." },
      { termino: "Кубометр (м³)", definicion: "Объем куба со стороной 1 метр." },
    ],
  };
};
