import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MEZCLA } from "../definicion";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const ft3 = 10 * 10 * (4 / 12);
        return [
          `За тераса од 10 × 10 стапки со дебелина од 4 инчи се потребни ${n(ft3)} куб. стапки бетон, односно ${n(ft3 / 27)} куб. јарди.`,
          `Со референтната мешавина тоа е околу ${n((MEZCLA.cementoKg * ft3 * 0.0283168466) / 0.45359237, 0)} фунти цемент.`,
        ];
      })()
    : (() => {
        const volumen = 4 * 3 * 0.1;
        return [
          `За плоча од 4 × 3 м со дебелина од 10 см се потребни ${n(volumen, 1)} м³ бетон.`,
          `Со референтната мешавина тоа е околу ${n(MEZCLA.cementoKg * volumen, 0)} кг цемент, ${n(MEZCLA.arenaM3 * volumen)} м³ песок и ${n(MEZCLA.piedraM3 * volumen)} м³ чакал.`,
        ];
      })();
  return {
    h1: "Калкулатор за бетон",
    title: tituloQueEntre(`Калкулатор за бетон: ${ctx.nombrePais}`, "Калкулатор за бетон: м³ и цемент", "Калкулатор за бетон"),
    description: `Пресметајте колку бетон ви треба за плоча, во ${imperial ? "кубни јарди" : "кубни метри"}, и приближно колку цемент, песок и чакал да купите.`,
    intro: [
      "Внесете ја должината, ширината и дебелината. Ќе го видите волуменот на бетонот и приближните материјали за мешавината.",
      "Материјалите зависат од рецептот. Калкулаторот користи како ориентир мешавина 1:2:3 за општа намена.",
    ],
    comoSeCalcula: [
      imperial
        ? "Волумен = должина × ширина × дебелина, со дебелината во стапки. Поделете ги кубните стапки со 27 за да добиете кубни јарди."
        : "Волумен = должина × ширина × дебелина, со дебелината во метри.",
      "Се додава резерва за нерамна подлога и истурање.",
      `На м³: околу ${MEZCLA.cementoKg} кг цемент, ${n(MEZCLA.arenaM3)} м³ песок, ${n(MEZCLA.piedraM3, 1)} м³ чакал и ${MEZCLA.aguaL} литри вода.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Колку цемент има во еден кубик бетон?",
        respuesta: `Со мешавина 1:2:3, околу ${MEZCLA.cementoKg} кг. Поцврстиот бетон бара повеќе цемент.`,
      },
      {
        pregunta: "Како се пресметува кубатурата на бетонот?",
        respuesta: `Помножете ја должината со ширината и со дебелината, сè во метри. Плоча од 5 × 4 м со дебелина од 12 см има волумен од ${n(5 * 4 * 0.12, 1)} м³. Додајте резерва од 5 % до 10 %.`,
      },
      {
        pregunta: "Дали да нарачам готов бетон?",
        respuesta: "За големи количини, готовиот бетон од бетонска база обично е порамномерен и побрз. За мали работи вообичаено е да се меша на самото место со овие количини.",
      },
    ],
    glosario: [
      { termino: "Рецепт за бетон", definicion: "Односот меѓу цемент, песок, чакал и вода во мешавината." },
      { termino: "Кубик", definicion: "Разговорен назив за кубен метар (м³), мерка за продажба на бетонот." },
    ],
  };
};
