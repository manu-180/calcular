import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MEZCLA } from "../definicion";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const ft3 = 10 * 10 * (4 / 12);
        return [
          `Για βεράντα 10 × 10 ft με πάχος 4 in χρειάζεστε ${n(ft3)} ft³ σκυροδέματος, δηλαδή ${n(ft3 / 27)} κυβικές γιάρδες.`,
          `Με το μείγμα του παραδείγματος θέλετε περίπου ${n((MEZCLA.cementoKg * ft3 * 0.0283168466) / 0.45359237, 0)} lb τσιμέντου.`,
        ];
      })()
    : (() => {
        const volumen = 4 * 3 * 0.1;
        return [
          `Για πλάκα 4 × 3 m με πάχος 10 cm χρειάζεστε ${n(volumen, 1)} m³ σκυροδέματος.`,
          `Με το μείγμα του παραδείγματος θέλετε περίπου ${n(MEZCLA.cementoKg * volumen, 0)} kg τσιμέντου, ${n(MEZCLA.arenaM3 * volumen)} m³ άμμου και ${n(MEZCLA.piedraM3 * volumen)} m³ χαλικιού.`,
        ];
      })();
  return {
    h1: "Υπολογισμός σκυροδέματος (μπετόν)",
    title: tituloQueEntre(`Υπολογισμός σκυροδέματος: ${ctx.nombrePais}`, "Υπολογισμός σκυροδέματος και τσιμέντου", "Υπολογισμός σκυροδέματος"),
    description: `Υπολογίστε πόσο σκυρόδεμα χρειάζεστε για μια πλάκα σε ${imperial ? "κυβικές γιάρδες" : "κυβικά μέτρα"} και περίπου πόσο τσιμέντο, άμμο και χαλίκι να αγοράσετε.`,
    intro: [
      "Εισάγετε μήκος, πλάτος και πάχος. Θα δείτε τον όγκο του σκυροδέματος και τις κατά προσέγγιση ποσότητες υλικών για το μείγμα.",
      "Οι ποσότητες εξαρτώνται από την αναλογία του μείγματος. Ο υπολογισμός χρησιμοποιεί ως παράδειγμα το συνηθισμένο μείγμα 1 : 2 : 3.",
    ],
    comoSeCalcula: [
      imperial
        ? "Όγκος = μήκος × πλάτος × πάχος, με το πάχος σε πόδια. Τα κυβικά πόδια διαιρούνται με το 27 για να βγουν κυβικές γιάρδες."
        : "Όγκος = μήκος × πλάτος × πάχος, με το πάχος σε μέτρα.",
      "Στον όγκο προστίθεται ένα περιθώριο για το ανώμαλο έδαφος και τις απώλειες.",
      `Για 1 m³ χρειάζονται περίπου ${MEZCLA.cementoKg} kg τσιμέντου, ${n(MEZCLA.arenaM3)} m³ άμμου, ${n(MEZCLA.piedraM3, 1)} m³ χαλικιού και ${MEZCLA.aguaL} λίτρα νερού.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Πόσο τσιμέντο χρειάζεται για 1 m³ σκυροδέματος;",
        respuesta: `Με μείγμα 1 : 2 : 3 περίπου ${MEZCLA.cementoKg} kg. Για πιο ανθεκτικό σκυρόδεμα χρειάζεται περισσότερο τσιμέντο.`,
      },
      {
        pregunta: "Πόσα κυβικά πόδια έχει μια κυβική γιάρδα;",
        respuesta: "27. Η κυβική γιάρδα είναι ένας κύβος 3 ft × 3 ft × 3 ft.",
      },
      {
        pregunta: "Αξίζει να παραγγείλω έτοιμο σκυρόδεμα;",
        respuesta: "Σε μεγαλύτερες σκυροδετήσεις το έτοιμο σκυρόδεμα από βαρέλα είναι πιο ομοιόμορφο και η δουλειά γίνεται πιο γρήγορα. Πουλιέται με το κυβικό. Σε μικρές εργασίες το μείγμα φτιάχνεται συνήθως επί τόπου με αυτές τις αναλογίες.",
      },
    ],
    glosario: [
      { termino: "Αναλογία μείγματος", definicion: "Η σχέση τσιμέντου, άμμου, χαλικιού και νερού στο μείγμα." },
      { termino: "Κυβικό μέτρο (m³)", definicion: "Ο όγκος ενός κύβου με ακμή 1 μέτρο, το «κυβικό» της οικοδομής." },
    ],
  };
};
