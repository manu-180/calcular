import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MEZCLA } from "../definicion";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const ft3 = 10 * 10 * (4 / 12);
        return [
          `За тераса 10 × 10 фута с дебелина 4 инча са нужни ${n(ft3)} куб. фута бетон, тоест ${n(ft3 / 27)} куб. ярда.`,
          `С референтната смес това са около ${n((MEZCLA.cementoKg * ft3 * 0.0283168466) / 0.45359237, 0)} фунта цимент.`,
        ];
      })()
    : (() => {
        const volumen = 4 * 3 * 0.1;
        return [
          `За плоча 4 × 3 м с дебелина 10 см са нужни ${n(volumen, 1)} м³ бетон.`,
          `С референтната смес това са около ${n(MEZCLA.cementoKg * volumen, 0)} кг цимент, ${n(MEZCLA.arenaM3 * volumen)} м³ пясък и ${n(MEZCLA.piedraM3 * volumen)} м³ чакъл.`,
        ];
      })();
  return {
    h1: "Калкулатор за бетон",
    title: tituloQueEntre(`Калкулатор за бетон: ${ctx.nombrePais}`, "Калкулатор за бетон: обем и цимент", "Калкулатор за бетон"),
    description: `Изчислете колко бетон Ви трябва за плоча, в ${imperial ? "кубични ярдове" : "кубични метри"}, и приблизително колко цимент, пясък и чакъл да купите.`,
    intro: [
      "Въведете дължината, ширината и дебелината. Ще видите обема на бетона и приблизителните материали за сместа.",
      "Материалите зависят от рецептата. Калкулаторът използва за ориентир смес 1:2:3 с обща употреба.",
    ],
    comoSeCalcula: [
      imperial
        ? "Обем = дължина × ширина × дебелина, с дебелината във футове. Разделете кубичните футове на 27, за да получите кубични ярдове."
        : "Обем = дължина × ширина × дебелина, с дебелината в метри.",
      "Добавя се резервът за неравна основа и разливане.",
      `На м³: около ${MEZCLA.cementoKg} кг цимент, ${n(MEZCLA.arenaM3)} м³ пясък, ${n(MEZCLA.piedraM3, 1)} м³ чакъл и ${MEZCLA.aguaL} литра вода.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Колко цимент има в един кубик бетон?",
        respuesta: `При смес 1:2:3 около ${MEZCLA.cementoKg} кг. По-здравият бетон изисква повече цимент.`,
      },
      {
        pregunta: "Как се смята кубатурата на бетон?",
        respuesta: `Умножете дължината по ширината и по дебелината, всичко в метри. Плоча 5 × 4 м с дебелина 12 см има обем ${n(5 * 4 * 0.12, 1)} м³. Добавете 5% до 10% резерв.`,
      },
      {
        pregunta: "Да поръчам ли готов бетон?",
        respuesta: "При големи обеми готовият бетон от бетонов възел обикновено е по-равномерен и по-бърз. При малки работи е обичайно да се бърка на място с тези количества.",
      },
    ],
    glosario: [
      { termino: "Рецепта на бетона", definicion: "Съотношението между цимент, пясък, чакъл и вода в сместа." },
      { termino: "Кубик", definicion: "Разговорно название за кубичен метър (м³), мярката, в която се продава бетонът." },
    ],
  };
};
