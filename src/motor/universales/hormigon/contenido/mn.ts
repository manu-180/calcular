import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MEZCLA } from "../definicion";

export const contenidoMn: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const ft3 = 10 * 10 * (4 / 12);
        return [
          `10 × 10 фут хэмжээтэй, 4 инч зузаан дэнжид ${n(ft3)} куб фут бетон хэрэгтэй, өөрөөр хэлбэл ${n(ft3 / 27)} куб ярд болно.`,
          `Жишиг хольцоор энэ нь ойролцоогоор ${n((MEZCLA.cementoKg * ft3 * 0.0283168466) / 0.45359237, 0)} фунт цемент юм.`,
        ];
      })()
    : (() => {
        const volumen = 4 * 3 * 0.1;
        return [
          `4 × 3 м хэмжээтэй, 10 см зузаан хавтанд ${n(volumen, 1)} м³ бетон хэрэгтэй.`,
          `Жишиг хольцоор энэ нь ойролцоогоор ${n(MEZCLA.cementoKg * volumen, 0)} кг цемент, ${n(MEZCLA.arenaM3 * volumen)} м³ элс, ${n(MEZCLA.piedraM3 * volumen)} м³ хайрга юм.`,
        ];
      })();
  return {
    h1: "Бетоны тооцоолуур",
    title: tituloQueEntre(`Бетоны тооцоолуур: ${ctx.nombrePais}`, "Бетоны тооцоолуур: эзлэхүүн, цемент", "Бетоны тооцоолуур"),
    description: `Хавтанд хэдий хэмжээний бетон хэрэгтэйг ${imperial ? "куб ярдаар" : "шоо метрээр"} болон хэр их цемент, элс, хайрга авахаа ойролцоогоор тооцоолно уу.`,
    intro: [
      "Урт, өргөн, зузаанаа оруулна уу. Бетоны эзлэхүүн болон хольцын ойролцоо материалыг харна.",
      "Материал нь жороос хамаарна. Тооцоолуур нь чиглүүлэг болгож ерөнхий зориулалтын 1:2:3 хольцыг ашигладаг.",
    ],
    comoSeCalcula: [
      imperial
        ? "Эзлэхүүн = урт × өргөн × зузаан, зузааныг футээр авна. Куб ярд гаргахын тулд куб футыг 27 хуваана."
        : "Эзлэхүүн = урт × өргөн × зузаан, зузааныг метрээр авна.",
      "Тэгш бус суурь, асгаралтад зориулсан нөөцийг нэмнэ.",
      `Нэг м³ тутамд: ойролцоогоор ${MEZCLA.cementoKg} кг цемент, ${n(MEZCLA.arenaM3)} м³ элс, ${n(MEZCLA.piedraM3, 1)} м³ хайрга, ${MEZCLA.aguaL} литр ус.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Нэг куб бетонд хэр их цемент ордог вэ?",
        respuesta: `1:2:3 хольцод ойролцоогоор ${MEZCLA.cementoKg} кг. Илүү бат бөх бетонд илүү их цемент орно.`,
      },
      {
        pregunta: "Бетоны кубыг яаж тооцоолох вэ?",
        respuesta: `Урт, өргөн, зузааныг бүгдийг метрээр авч үржүүлнэ. 5 × 4 м хэмжээтэй, 12 см зузаан хавтангийн эзлэхүүн ${n(5 * 4 * 0.12, 1)} м³ байна. 5 ба 10 хувийн хооронд нөөц нэмнэ үү.`,
      },
      {
        pregunta: "Бэлэн бетон захиалах уу?",
        respuesta: "Их хэмжээний ажилд үйлдвэрийн бэлэн бетон ихэвчлэн илүү жигд, хурдан байдаг. Жижиг ажилд эдгээр хэмжээгээр газар дээр нь зуурах нь түгээмэл.",
      },
    ],
    glosario: [
      { termino: "Бетоны жор", definicion: "Хольц дахь цемент, элс, хайрга, усны харьцаа." },
      { termino: "Куб", definicion: "Шоо метрийн (м³) ярианы нэр, бетоныг энэ хэмжээгээр зардаг." },
    ],
  };
};
