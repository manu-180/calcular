import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const antes = montoEjemplo(ctx, 40);
  const despues = antes * 1.25;
  const m = (n: number) => formatearMonto(ctx, n);
  const n = (x: number) => formatearNumero(ctx, x);
  const subida = ((despues - antes) / antes) * 100;
  const vuelta = ((despues - antes) / despues) * 100;
  return {
    h1: "Калькулятор изменения в процентах",
    title: tituloQueEntre(`Изменение в процентах онлайн: ${ctx.nombrePais}`, "Калькулятор изменения в процентах", "Изменение в процентах"),
    description: "Посчитайте, на сколько процентов выросло или снизилось значение: цена, зарплата, продажи или любое число, которое изменилось со временем.",
    intro: [
      "Введите старое и новое значение. Вы увидите рост или снижение в процентах и разницу между числами.",
      "Калькулятор также показывает, на сколько процентов нужно изменить значение, чтобы вернуться к исходному. Почти никогда это не тот же процент.",
    ],
    comoSeCalcula: [
      "Изменение в процентах = (новое значение − старое значение) ÷ старое значение × 100.",
      "Положительный результат означает рост, отрицательный означает снижение.",
      "Если старое значение отрицательное, делим на его модуль, чтобы знак по-прежнему показывал, стало лучше или хуже.",
    ],
    ejemplo: [
      `Товар стоил ${m(antes)}, а теперь стоит ${m(despues)}. Он подорожал на ${n(subida)}%.`,
      `Чтобы вернуться к прежней цене, он должен подешеветь на ${n(vuelta)}%, а не на ${n(subida)}%.`,
    ],
    faq: [
      {
        pregunta: "Как посчитать рост в процентах?",
        respuesta: `Вычтите старое значение из нового, разделите на старое и умножьте на 100. С 80 до 100: 20 ÷ 80 × 100 = ${n((20 / 80) * 100)}%.`,
      },
      {
        pregunta: "Как посчитать снижение в процентах?",
        respuesta: `Формула та же. Со 100 до 80: −20 ÷ 100 × 100 = −${n(20)}%, то есть значение снизилось на ${n(20)}%.`,
      },
      {
        pregunta: "Почему рост на 25% и снижение на 25% не компенсируют друг друга?",
        respuesta: `Каждый процент берется от своей базы. 80 плюс 25% равно 100, но 100 минус 25% равно ${n(100 * 0.75)}.`,
      },
      {
        pregunta: "Чем проценты отличаются от процентных пунктов?",
        respuesta: `Если ставка выросла с 10% до 12%, она прибавила 2 процентных пункта. А в процентах она выросла на ${n(((12 - 10) / 10) * 100)}%.`,
      },
    ],
    glosario: [
      { termino: "Изменение в процентах", definicion: "На сколько изменилось значение, в процентах от исходного." },
      { termino: "Процентный пункт", definicion: "Простая разница между двумя процентами." },
    ],
  };
};
