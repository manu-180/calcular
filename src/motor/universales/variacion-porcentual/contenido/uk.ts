import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const antes = montoEjemplo(ctx, 40);
  const despues = antes * 1.25;
  const m = (n: number) => formatearMonto(ctx, n);
  const n = (x: number) => formatearNumero(ctx, x);
  const subida = ((despues - antes) / antes) * 100;
  const vuelta = ((despues - antes) / despues) * 100;
  return {
    h1: "Калькулятор зміни у відсотках",
    title: tituloQueEntre(`Калькулятор зміни у відсотках (${ctx.nombrePais})`, "Калькулятор зміни у відсотках", "Зміна у відсотках"),
    description: "Розрахуйте, на скільки відсотків зросло чи зменшилося значення: ціна, зарплата, продажі чи будь-яке число, що змінилося з часом.",
    intro: [
      "Введіть старе і нове значення. Ви побачите зростання чи зменшення у відсотках і різницю.",
      "Калькулятор також показує, на скільки відсотків треба змінити значення, щоб повернутися до початкового. Це майже ніколи не той самий відсоток.",
    ],
    comoSeCalcula: [
      "Зміна у відсотках = (нове значення − старе значення) ÷ старе значення × 100.",
      "Додатний результат означає зростання, відʼємний означає зменшення.",
      "Якщо старе значення відʼємне, ділимо на його модуль, щоб знак і далі показував, покращилося значення чи погіршилося.",
    ],
    ejemplo: [
      `Товар, який коштував ${m(antes)}, а тепер коштує ${m(despues)}, подорожчав на ${n(subida)}%.`,
      `Щоб повернутися до старої ціни, він має подешевшати на ${n(vuelta)}%, а не на ${n(subida)}%.`,
    ],
    faq: [
      {
        pregunta: "Як розрахувати зростання у відсотках?",
        respuesta: `Відніміть старе значення від нового, поділіть на старе і помножте на 100. Від 80 до 100: 20 ÷ 80 × 100 = ${n((20 / 80) * 100)}%.`,
      },
      {
        pregunta: "Як розрахувати зменшення у відсотках?",
        respuesta: `Формула та сама. Від 100 до 80: −20 ÷ 100 × 100 = −${n(20)}%, тобто значення зменшилося на ${n(20)}%.`,
      },
      {
        pregunta: "Чому зростання на 25% і падіння на 25% не компенсують одне одного?",
        respuesta: `Кожен відсоток рахується від іншої бази. 80 плюс 25% дорівнює 100, а 100 мінус 25% дорівнює ${n(75)}.`,
      },
      {
        pregunta: "Чим відрізняються відсотки і відсоткові пункти?",
        respuesta: `Якщо ставка змінилася з 10% до 12%, вона зросла на 2 відсоткові пункти. А зміна у відсотках становить ${n(((12 - 10) / 10) * 100)}%.`,
      },
    ],
    glosario: [
      { termino: "Зміна у відсотках", definicion: "На скільки змінилося значення, у відсотках від початкового." },
      { termino: "Відсотковий пункт", definicion: "Проста різниця між двома відсотками." },
    ],
  };
};
