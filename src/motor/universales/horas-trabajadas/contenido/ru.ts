import { formaRu } from "../../../i18n/plural";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { horarios, minutosTrabajados } from "../definicion";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const m = (x: number) => formatearMonto(ctx, x);
  const n = (x: number, decimales = 0) => formatearNumero(ctx, x, decimales);
  const h = (x: number) => `${n(x)} ${formaRu(x, "час", "часа", "часов", "часа")}`;
  const hora = (v: string) => horarios(ctx.locale).find((o) => o.valor === v)?.etiqueta ?? v;
  const pago = montoEjemplo(ctx, 15);
  const jornada = minutosTrabajados("09:00", "17:30", 30) / 60;
  const larga = minutosTrabajados("08:00", "18:00", 60) / 60;
  const extra = larga * 5 - 40;
  return {
    h1: "Калькулятор рабочего времени",
    title: tituloQueEntre(`Учет рабочего времени: ${ctx.nombrePais}`, "Калькулятор рабочего времени", "Учет рабочего времени"),
    description: "Посчитайте отработанные за неделю часы по времени начала, окончания и перерывам и рассчитайте оплату со сверхурочными.",
    intro: [
      "Выберите время начала и окончания работы для каждого дня, неоплачиваемый перерыв и оплату за час. Мы покажем общее число часов, сверхурочные и оплату за неделю.",
      "Расчет поможет проверить зарплату, заполнить табель или выставить счет за почасовую работу.",
    ],
    comoSeCalcula: [
      "Часы за день = окончание − начало − перерыв. Если окончание раньше начала, смена закончилась на следующий день.",
      "Сверхурочные = итог за неделю − нормальные часы, если итог их превышает.",
      "Оплата = нормальные часы × оплата за час + сверхурочные часы × оплата за час × (1 + надбавка).",
    ],
    ejemplo: [
      `С ${hora("09:00")} до ${hora("17:30")} с перерывом 30 минут получается ${h(jornada)} в день. С понедельника по пятницу это ${h(jornada * 5)}, и при оплате ${m(pago)} за час выходит ${m(jornada * 5 * pago)}.`,
      `С ${hora("08:00")} до ${hora("18:00")} с часовым перерывом за неделю набирается ${h(larga * 5)}, из них сверхурочных ${n(extra)}. При полуторной оплате выходит ${m(40 * pago + extra * pago * 1.5)}.`,
    ],
    faq: [
      {
        pregunta: "Как посчитать отработанные часы?",
        respuesta: "Вычтите время начала из времени окончания и отнимите перерыв. Затем сложите все дни недели.",
      },
      {
        pregunta: "Как перевести минуты в десятичные часы?",
        respuesta: `Разделите минуты на 60. Полчаса равны ${n(0.5, 1)} часа, 15 минут равны ${n(0.25, 2)}, 45 минут равны ${n(0.75, 2)}. Значит, 7 часов 45 минут составляют ${n(7.75, 2)} часа.`,
      },
      {
        pregunta: "Сколько можно работать сверхурочно и как это оплачивается?",
        respuesta: "Это зависит от закона страны, где вы работаете, и от трудового договора. Калькулятор использует ту надбавку и норму часов, которые вы ввели, и не применяет правила какой-то конкретной страны.",
      },
    ],
    glosario: [
      { termino: "Сверхурочная работа", definicion: "Часы сверх нормальной продолжительности, которые оплачиваются по повышенной ставке." },
      { termino: "Полуторная оплата", definicion: "Оплата сверхурочного часа в полтора раза выше обычной, то есть с надбавкой 50%." },
    ],
  };
};
