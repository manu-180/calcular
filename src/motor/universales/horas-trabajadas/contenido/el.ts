import { GRAMATICA } from "../../../i18n/gramatica";
import { formaEl } from "../../../i18n/plural";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { horarios, minutosTrabajados } from "../definicion";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const m = (x: number) => formatearMonto(ctx, x);
  const n = (x: number, decimales = 0) => formatearNumero(ctx, x, decimales);
  // «1 ώρα», «8 ώρες», «7,75 ώρες».
  const h = (x: number, decimales = 0) => `${n(x, decimales)} ${formaEl(x, "ώρα", "ώρες")}`;
  const hora = (v: string) => horarios(ctx.locale).find((o) => o.valor === v)?.etiqueta ?? v;
  const pago = montoEjemplo(ctx, 15);
  const jornada = minutosTrabajados("09:00", "17:30", 30) / 60;
  const larga = minutosTrabajados("08:00", "18:00", 60) / 60;
  const extra = larga * 5 - 40;
  return {
    h1: "Υπολογισμός ωρών εργασίας",
    title: tituloQueEntre(
      `Ώρες εργασίας: υπολογισμός ωραρίου και αμοιβής ${GRAMATICA.el.para(ctx.nombrePais)}`,
      `Ώρες εργασίας ${GRAMATICA.el.para(ctx.nombrePais)}`,
      "Υπολογισμός ωρών εργασίας",
    ),
    description: "Αθροίστε τις ώρες εργασίας της εβδομάδας με την ώρα έναρξης, λήξης και τα διαλείμματα και υπολογίστε την αμοιβή μαζί με τις υπερωρίες.",
    intro: [
      "Για κάθε ημέρα επιλέξτε ώρα έναρξης και λήξης, το απλήρωτο διάλειμμα και την ωριαία αμοιβή. Θα δείτε το σύνολο των ωρών, τις υπερωρίες και την αμοιβή της εβδομάδας.",
      "Χρησιμεύει για να ελέγξετε τη μισθοδοσία, να συμπληρώσετε φύλλο παρουσίας ή να τιμολογήσετε εργασία με την ώρα.",
    ],
    comoSeCalcula: [
      "Ώρες ανά ημέρα = λήξη − έναρξη − διάλειμμα. Αν η λήξη είναι πριν από την έναρξη, η βάρδια τελειώνει την επόμενη ημέρα.",
      "Υπερωρίες = σύνολο ωρών της εβδομάδας − κανονικές ώρες, όταν το σύνολο τις ξεπερνά.",
      "Αμοιβή = κανονικές ώρες × ωριαία αμοιβή + ώρες υπερωρίας × ωριαία αμοιβή × (1 + προσαύξηση).",
    ],
    ejemplo: [
      `Από ${hora("09:00")} έως ${hora("17:30")} με διάλειμμα 30 λεπτών βγαίνουν ${h(jornada)} την ημέρα. Από Δευτέρα έως Παρασκευή είναι ${h(jornada * 5)}: με αμοιβή ${m(pago)} την ώρα, το σύνολο είναι ${m(jornada * 5 * pago)}.`,
      `Από ${hora("08:00")} έως ${hora("18:00")} με διάλειμμα μίας ώρας βγαίνουν ${h(larga * 5)} την εβδομάδα, από τις οποίες ${h(extra)} υπερωρία. Με προσαύξηση 50% το σύνολο είναι ${m(40 * pago + extra * pago * 1.5)}.`,
    ],
    faq: [
      {
        pregunta: "Πώς υπολογίζονται οι ώρες εργασίας;",
        respuesta: "Από την ώρα λήξης αφαιρέστε την ώρα έναρξης και μετά το διάλειμμα. Στο τέλος αθροίστε όλες τις ημέρες της εβδομάδας.",
      },
      {
        pregunta: "Πώς μετατρέπονται τα λεπτά σε δεκαδικές ώρες;",
        respuesta: `Διαιρέστε τα λεπτά με το 60. Η μισή ώρα είναι ${n(0.5, 1)}, τα 15 λεπτά ${n(0.25, 2)} και τα 45 λεπτά ${n(0.75, 2)}. Άρα 7 ώρες και 45 λεπτά είναι ${h(7.75, 2)}.`,
      },
      {
        pregunta: "Πόσες υπερωρίες επιτρέπονται και πώς πληρώνονται;",
        respuesta: "Εξαρτάται από τη νομοθεσία της χώρας όπου εργάζεστε και από τη σύμβασή σας. Ο υπολογισμός χρησιμοποιεί την προσαύξηση και τις κανονικές ώρες που εισάγετε, χωρίς συγκεκριμένο νομικό κανόνα.",
      },
    ],
    glosario: [
      { termino: "Υπερωρία", definicion: "Εργασία πέρα από το κανονικό ωράριο, που πληρώνεται με προσαύξηση." },
      { termino: "Προσαύξηση 50%", definicion: "Αμοιβή υπερωρίας κατά το ήμισυ μεγαλύτερη από την κανονική, δηλαδή μιάμιση φορά την ωριαία αμοιβή." },
    ],
  };
};
