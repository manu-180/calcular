import { formaMk } from "../../../i18n/plural";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { horarios, minutosTrabajados } from "../definicion";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const m = (x: number) => formatearMonto(ctx, x);
  const n = (x: number, decimales = 0) => formatearNumero(ctx, x, decimales);
  const h = (x: number) => `${n(x)} ${formaMk(x, "час", "часа")}`;
  const hora = (v: string) => horarios(ctx.locale).find((o) => o.valor === v)?.etiqueta ?? v;
  const pago = montoEjemplo(ctx, 15);
  const jornada = minutosTrabajados("09:00", "17:30", 30) / 60;
  const larga = minutosTrabajados("08:00", "18:00", 60) / 60;
  const extra = larga * 5 - 40;
  return {
    h1: "Калкулатор за работни часови",
    title: tituloQueEntre(`Работни часови: калкулатор, ${ctx.nombrePais}`, "Калкулатор за работни часови", "Работни часови"),
    description: "Соберете ги работните часови за неделата според почетокот, крајот и паузата и пресметајте го плаќањето, со прекувремената работа.",
    intro: [
      "Изберете почеток и крај за секој ден, неплатената пауза и плаќањето по час. Ќе ги видите вкупните часови, прекувремената работа и плаќањето за неделата.",
      "Користете го за да ја проверите платата, да пополните евиденција на работно време или да фактурирате работа по час.",
    ],
    comoSeCalcula: [
      "Часови на ден = крај − почеток − пауза. Ако крајот е порано од почетокот, смената завршува следниот ден.",
      "Прекувремена работа = вкупно часови за неделата − редовни часови, кога вкупниот број ги надминува.",
      "Плаќање = редовни часови × плаќање по час + прекувремени часови × плаќање по час × (1 + додаток).",
    ],
    ejemplo: [
      `Од ${hora("09:00")} до ${hora("17:30")} со 30 минути пауза се ${h(jornada)} на ден. Од понеделник до петок тоа се ${h(jornada * 5)}: со ${m(pago)} по час тоа изнесува ${m(jornada * 5 * pago)}.`,
      `Од ${hora("08:00")} до ${hora("18:00")} со еден час пауза се ${h(larga * 5)} неделно, од кои ${h(extra)} се прекувремена работа. Со час и пол, плаќањето е ${m(40 * pago + extra * pago * 1.5)}.`,
    ],
    faq: [
      {
        pregunta: "Како се пресметуваат работните часови?",
        respuesta: "Одземете го часот на почеток од часот на крај и одземете ја паузата. Потоа соберете ги сите денови од неделата.",
      },
      {
        pregunta: "Како да ги претворам минутите во децимални часови?",
        respuesta: `Поделете ги минутите со 60. Половина час е ${n(0.5, 1)}, 15 минути се ${n(0.25, 2)}, а 45 минути се ${n(0.75, 2)}. Така, 7 часа и 45 минути се ${n(7.75, 2)} часа.`,
      },
      {
        pregunta: "Колку прекувремена работа смеам да работам и како се плаќа?",
        respuesta: "Тоа зависи од законот таму каде што работите и од вашиот договор. Калкулаторот ги користи додатокот и редовните часови што ќе ги внесете, без да применува конкретно правило.",
      },
    ],
    glosario: [
      { termino: "Прекувремена работа", definicion: "Часови над редовното работно време, кои се плаќаат со додаток." },
      { termino: "Час и пол", definicion: "Плаќање на прекувремениот час во износ од еден и пол пати од редовниот, односно додаток од 50 %." },
    ],
  };
};
