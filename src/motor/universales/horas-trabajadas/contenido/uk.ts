import { GRAMATICA } from "../../../i18n/gramatica";
import { formaUk } from "../../../i18n/plural";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { horarios, minutosTrabajados } from "../definicion";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const m = (x: number) => formatearMonto(ctx, x);
  const n = (x: number, decimales = 0) => formatearNumero(ctx, x, decimales);
  const h = (x: number, decimales = 0) => `${n(x, decimales)} ${formaUk(Number.isInteger(x) ? x : 1.5, "година", "години", "годин")}`;
  const hora = (v: string) => horarios(ctx.locale).find((o) => o.valor === v)?.etiqueta ?? v;
  const pago = montoEjemplo(ctx, 15);
  const jornada = minutosTrabajados("09:00", "17:30", 30) / 60;
  const larga = minutosTrabajados("08:00", "18:00", 60) / 60;
  const extra = larga * 5 - 40;
  return {
    h1: "Калькулятор обліку робочого часу",
    title: tituloQueEntre(
      `Облік робочого часу: калькулятор годин ${GRAMATICA.uk.para(ctx.nombrePais)}`,
      `Облік робочого часу ${GRAMATICA.uk.para(ctx.nombrePais)}`,
      "Калькулятор обліку робочого часу",
    ),
    description: "Порахуйте відпрацьовані за тиждень години за часом початку, завершення і перервами та розрахуйте оплату разом із понаднормовими.",
    intro: [
      "Оберіть час початку і завершення для кожного дня, неоплачувану перерву й оплату за годину. Ми покажемо загальну кількість годин, понаднормові та оплату за тиждень.",
      "Це допомагає перевірити зарплату, заповнити табель або виставити рахунок за погодинну роботу.",
    ],
    comoSeCalcula: [
      "Годин за день = завершення − початок − перерва. Якщо завершення раніше за початок, зміна закінчується наступного дня.",
      "Понаднормові = загальна кількість за тиждень − нормальні години, якщо загальна кількість їх перевищує.",
      "Оплата = нормальні години × оплата за годину + понаднормові години × оплата за годину × (1 + доплата).",
    ],
    ejemplo: [
      `З ${hora("09:00")} до ${hora("17:30")} з перервою 30 хвилин виходить ${h(jornada)} на день. З понеділка по пʼятницю ${h(jornada * 5)}: за ставки ${m(pago)} на годину це ${m(jornada * 5 * pago)}.`,
      `З ${hora("08:00")} до ${hora("18:00")} з перервою на годину виходить ${h(larga * 5)} на тиждень, з них понаднормових ${n(extra)}. У півторному розмірі це ${m(40 * pago + extra * pago * 1.5)}.`,
    ],
    faq: [
      {
        pregunta: "Як порахувати відпрацьовані години?",
        respuesta: "Відніміть час початку від часу завершення і відніміть перерву. Потім додайте всі дні тижня.",
      },
      {
        pregunta: "Як перевести хвилини в десяткові години?",
        respuesta: `Поділіть хвилини на 60. Пів години дорівнює ${n(0.5, 1)}, 15 хвилин ${n(0.25, 2)}, 45 хвилин ${n(0.75, 2)}. Тож 7 годин 45 хвилин є ${h(7.75, 2)}.`,
      },
      {
        pregunta: "Скільки можна працювати понаднормово і як це оплачується?",
        respuesta: "Це залежить від закону країни, де ви працюєте, і від вашого договору. Калькулятор використовує доплату і нормальні години, які ви вводите, без застосування конкретного правила.",
      },
    ],
    glosario: [
      { termino: "Понаднормові години", definicion: "Години понад нормальну тривалість роботи, які оплачуються за підвищеною ставкою." },
      { termino: "Півторний розмір", definicion: "Оплата понаднормових у півтора раза більша за звичайну, тобто з доплатою 50%." },
    ],
  };
};
