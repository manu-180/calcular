import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { DEFICIT, FACTORES, mifflin, SUPERAVIT } from "../definicion";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 0) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const basal = mifflin("hombre", 35, 180 * 0.45359237, 70 * 2.54);
        return [
          `Ένας άνδρας 35 ετών με βάρος 180 lb και ύψος 5 ft 10 in έχει βασικό μεταβολισμό περίπου ${n(basal)} kcal.`,
          `Αν κινείται λίγο, για να διατηρήσει το βάρος του χρειάζεται περίπου ${n(basal * FACTORES.sedentaria)} kcal την ημέρα.`,
        ];
      })()
    : (() => {
        const basal = mifflin("mujer", 30, 60, 165);
        return [
          `Μια γυναίκα 30 ετών με βάρος 60 kg και ύψος 165 cm έχει βασικό μεταβολισμό περίπου ${n(basal)} kcal.`,
          `Με μέτρια δραστηριότητα, για να διατηρήσει το βάρος της χρειάζεται περίπου ${n(basal * FACTORES.moderada)} kcal την ημέρα.`,
        ];
      })();
  return {
    h1: "Υπολογισμός θερμίδων: ημερήσιες ανάγκες",
    title: tituloQueEntre(`Υπολογισμός θερμίδων ημέρας (${ctx.nombrePais})`, "Υπολογισμός θερμίδων: ημερήσιες ανάγκες", "Υπολογισμός θερμίδων"),
    description: "Δείτε πόσες θερμίδες καίτε την ημέρα και πόσες χρειάζεστε για να διατηρήσετε, να χάσετε ή να πάρετε βάρος.",
    intro: [
      "Εισάγετε τα στοιχεία σας και το επίπεδο δραστηριότητας. Θα δείτε τον βασικό μεταβολισμό και πόσες θερμίδες καίτε σε μια συνηθισμένη ημέρα.",
      "Πρόκειται για ενδεικτική εκτίμηση. Δεν αντικαθιστά τη συμβουλή γιατρού ή διαιτολόγου.",
    ],
    comoSeCalcula: [
      `Βασικός μεταβολισμός (Mifflin-St Jeor): 10 × βάρος σε kg + ${n(6.25, 2)} × ύψος σε cm − 5 × ηλικία. Στους άνδρες προστίθενται 5 και στις γυναίκες αφαιρούνται 161.`,
      `Θερμίδες διατήρησης = βασικός μεταβολισμός × συντελεστής δραστηριότητας. Ο συντελεστής πηγαίνει από ${n(1.2, 1)} (ελάχιστη δραστηριότητα) έως ${n(1.9, 1)} (πολύ υψηλή).`,
      `Για απώλεια βάρους αφαιρούνται ${DEFICIT} kcal την ημέρα και για αύξηση προστίθενται ${SUPERAVIT} kcal: μια ήπια αλλαγή που μπορείτε να κρατήσετε για καιρό.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Τι είναι ο βασικός μεταβολισμός;",
        respuesta: "Είναι η ενέργεια που καταναλώνει ο οργανισμός σε πλήρη ηρεμία για την αναπνοή, τη διατήρηση της θερμοκρασίας και τη λειτουργία των οργάνων.",
      },
      {
        pregunta: "Πόσες θερμίδες να τρώω για να χάσω βάρος;",
        respuesta: `Ένα συνηθισμένο σημείο εκκίνησης είναι περίπου ${DEFICIT} kcal την ημέρα λιγότερες από τις θερμίδες διατήρησης. Το καλύτερο είναι να το ορίσετε μαζί με έναν επαγγελματία υγείας.`,
      },
      {
        pregunta: "Πόσο ακριβής είναι ο τύπος;",
        respuesta: "Ο τύπος Mifflin-St Jeor είναι από τους πιο διαδεδομένους, αλλά δίνει μια μέση τιμή. Η γενετική, η μυϊκή μάζα και η κατάσταση της υγείας αλλάζουν το πόσες θερμίδες καίτε πραγματικά.",
      },
    ],
    glosario: [
      { termino: "Θερμίδα (kcal)", definicion: "Μονάδα ενέργειας που περιέχουν οι τροφές και καταναλώνει ο οργανισμός." },
      { termino: "Βασικός μεταβολισμός", definicion: "Οι θερμίδες που καίει ο οργανισμός σε πλήρη ηρεμία." },
    ],
  };
};
