import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { DEFICIT, FACTORES, mifflin, SUPERAVIT } from "../definicion";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 0) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const basal = mifflin("hombre", 35, 180 * 0.45359237, 70 * 2.54);
        return [
          `Маж на 35 години со тежина 180 lb и висина 5 ft 10 in има базален метаболизам околу ${n(basal)} kcal.`,
          `Со малку движење ја задржува тежината со околу ${n(basal * FACTORES.sedentaria)} kcal на ден.`,
        ];
      })()
    : (() => {
        const basal = mifflin("mujer", 30, 60, 165);
        return [
          `Жена на 30 години со тежина 60 kg и висина 165 cm има базален метаболизам околу ${n(basal)} kcal.`,
          `Со умерена активност ја задржува тежината со околу ${n(basal * FACTORES.moderada)} kcal на ден.`,
        ];
      })();
  return {
    h1: "Калкулатор за дневни калории",
    title: tituloQueEntre(`Калкулатор за калории ${GRAMATICA.mk.en(ctx.nombrePais)}`, "Калкулатор за калории", "Дневни калории"),
    description: "Пресметајте колку калории согорувате на ден според возраст, тежина, висина и активност и колку да внесете за да ја задржите или смените тежината.",
    intro: [
      "Внесете ги вашите податоци и нивото на активност. Ќе го видите базалниот метаболизам и калориите што ги согорувате во обичен ден.",
      "Ова е приближна проценка. Не заменува консултација со лекар или нутриционист.",
    ],
    comoSeCalcula: [
      `Базален метаболизам (Мифлин-Сан Жеор): 10 × тежина во kg + ${n(6.25, 2)} × висина во cm − 5 × возраст, плус 5 кај мажите или минус 161 кај жените.`,
      `Калории за одржување = базален метаболизам × коефициент на активност, од ${n(1.2, 1)} (малку движење) до ${n(1.9, 1)} (многу висока активност).`,
      `За слабеење се одземаат ${DEFICIT} kcal на ден, а за зголемување на тежината се додаваат ${SUPERAVIT}: умерена промена што може да се одржи.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Што е базален метаболизам?",
        respuesta: "Тоа е енергијата што телото ја троши во целосно мирување за да дише, да ја одржува температурата и да работат органите.",
      },
      {
        pregunta: "Колку калории да внесувам за да ослабам?",
        respuesta: `Вообичаена почетна точка е околу ${DEFICIT} kcal на ден под калориите за одржување. Најдобро е вредноста да ја одредите заедно со стручно лице.`,
      },
      {
        pregunta: "Колку е точна формулата?",
        respuesta: "Формулата Мифлин-Сан Жеор е една од најкористените, но дава просечна вредност. Генетиката, мускулната маса и здравствената состојба ја менуваат реалната потрошувачка.",
      },
    ],
    glosario: [
      { termino: "Калорија (kcal)", definicion: "Мерна единица за енергијата во храната и за она што телото го согорува." },
      { termino: "Базален метаболизам", definicion: "Калориите што телото ги согорува во целосно мирување." },
    ],
  };
};
