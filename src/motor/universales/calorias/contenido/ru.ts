import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { DEFICIT, FACTORES, mifflin, SUPERAVIT } from "../definicion";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 0) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const basal = mifflin("hombre", 35, 180 * 0.45359237, 70 * 2.54);
        return [
          `У мужчины 35 лет с весом 180 фунтов и ростом 5 футов 10 дюймов базовый обмен составляет около ${n(basal)} ккал.`,
          `При низкой активности он сохраняет вес примерно на ${n(basal * FACTORES.sedentaria)} ккал в день.`,
        ];
      })()
    : (() => {
        const basal = mifflin("mujer", 30, 60, 165);
        return [
          `У женщины 30 лет с весом 60 кг и ростом 165 см базовый обмен составляет около ${n(basal)} ккал.`,
          `При средней активности она сохраняет вес примерно на ${n(basal * FACTORES.moderada)} ккал в день.`,
        ];
      })();
  return {
    h1: "Калькулятор калорий в день",
    title: tituloQueEntre(`Калькулятор калорий: ${ctx.nombrePais}`, "Калькулятор калорий в день", "Калькулятор калорий"),
    description: "Рассчитайте суточную норму калорий по возрасту, весу, росту и активности и узнайте, сколько есть, чтобы сохранить, снизить или набрать вес.",
    intro: [
      "Введите свои данные и уровень активности. Калькулятор покажет базовый обмен веществ и сколько калорий вы тратите в обычный день.",
      "Это приблизительная оценка. Результат не заменяет консультацию врача или диетолога.",
    ],
    comoSeCalcula: [
      `Базовый обмен (формула Миффлина-Сан Жеора) = 10 × вес в кг + ${n(6.25, 2)} × рост в см − 5 × возраст, плюс 5 для мужчин или минус 161 для женщин.`,
      `Калории для сохранения веса = базовый обмен × коэффициент активности, от ${n(1.2, 1)} (низкая активность) до ${n(1.9, 1)} (очень высокая).`,
      `Для снижения веса калькулятор вычитает ${DEFICIT} ккал в день, для набора прибавляет ${SUPERAVIT}. Это умеренное изменение, которое легко поддерживать.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Что такое базовый обмен веществ?",
        respuesta: "Это энергия, которую организм тратит в полном покое на дыхание, поддержание температуры и работу органов.",
      },
      {
        pregunta: "Сколько калорий нужно в день, чтобы похудеть?",
        respuesta: `Обычно начинают с дефицита около ${DEFICIT} ккал в день от нормы для сохранения веса. Точную цифру лучше подобрать со специалистом.`,
      },
      {
        pregunta: "Насколько точна формула?",
        respuesta: "Формула Миффлина-Сан Жеора одна из самых распространенных, но она дает среднее значение. Наследственность, мышечная масса и здоровье меняют реальный расход.",
      },
    ],
    glosario: [
      { termino: "Калория (ккал)", definicion: "Единица энергии в еде и в том, что тратит организм." },
      { termino: "Базовый обмен", definicion: "Калории, которые организм сжигает в полном покое." },
    ],
  };
};
