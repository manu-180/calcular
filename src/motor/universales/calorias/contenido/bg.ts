import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { DEFICIT, FACTORES, mifflin, SUPERAVIT } from "../definicion";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 0) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const basal = mifflin("hombre", 35, 180 * 0.45359237, 70 * 2.54);
        return [
          `Мъж на 35 години с тегло 180 lb и ръст 5 ft 10 in има базален метаболизъм около ${n(basal)} kcal.`,
          `При малко движение той запазва теглото си с около ${n(basal * FACTORES.sedentaria)} kcal на ден.`,
        ];
      })()
    : (() => {
        const basal = mifflin("mujer", 30, 60, 165);
        return [
          `Жена на 30 години с тегло 60 kg и ръст 165 cm има базален метаболизъм около ${n(basal)} kcal.`,
          `При умерена активност тя запазва теглото си с около ${n(basal * FACTORES.moderada)} kcal на ден.`,
        ];
      })();
  return {
    h1: "Калкулатор за дневни калории",
    title: tituloQueEntre(`Калкулатор за калории ${GRAMATICA.bg.en(ctx.nombrePais)}`, "Калкулатор за калории", "Дневни калории"),
    description: "Изчислете колко калории изгаряте на ден според възраст, тегло, ръст и активност и колко да приемате, за да запазите, свалите или качите килограми.",
    intro: [
      "Попълнете данните си и нивото на активност. Ще видите базалния си метаболизъм и калориите, които изгаряте в обикновен ден.",
      "Това е ориентировъчна оценка. Тя не замества консултацията с лекар или специалист по хранене.",
    ],
    comoSeCalcula: [
      `Базален метаболизъм (Мифлин-Сан Жеор): 10 × тегло в kg + ${n(6.25, 2)} × ръст в cm − 5 × възраст, плюс 5 при мъжете или минус 161 при жените.`,
      `Калории за поддържане = базален метаболизъм × коефициент на активност, от ${n(1.2, 1)} (малко движение) до ${n(1.9, 1)} (много висока активност).`,
      `За отслабване се изваждат ${DEFICIT} kcal на ден, а за качване се добавят ${SUPERAVIT}: умерена промяна, която може да се поддържа.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Какво е базален метаболизъм?",
        respuesta: "Това е енергията, която тялото използва в пълен покой, за да диша, да поддържа температурата си и да работят органите.",
      },
      {
        pregunta: "Колко калории да приемам, за да отслабна?",
        respuesta: `Обичайна отправна точка е около ${DEFICIT} kcal на ден под калориите за поддържане. Най-добре е да определите стойността заедно със специалист.`,
      },
      {
        pregunta: "Колко точна е формулата?",
        respuesta: "Формулата на Мифлин-Сан Жеор е сред най-използваните, но дава средна стойност. Генетиката, мускулната маса и здравословното състояние променят реалния разход.",
      },
    ],
    glosario: [
      { termino: "Калория (kcal)", definicion: "Мерната единица за енергията в храната и за това, което изгаря тялото." },
      { termino: "Базален метаболизъм", definicion: "Калориите, които тялото изгаря в пълен покой." },
    ],
  };
};
