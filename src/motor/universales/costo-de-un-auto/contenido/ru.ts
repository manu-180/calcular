  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const g: GastosAuto = {
    precio: montoEjemplo(ctx, 25000),
    depreciacion: 15,
    seguro: montoEjemplo(ctx, 100),
    distancia: 1000,
    consumo: imperial ? 28 : 8,
    precioCombustible: montoEjemplo(ctx, imperial ? 3.5 : 1.2),
    mantenimiento: montoEjemplo(ctx, 60),
    estacionamiento: 0,
    otros: 0,
  };
  const mensual = costoMensual(g, imperial);
  const unidad = imperial ? "мили" : "километра";
  const distancia = imperial ? `${formatearNumero(ctx, g.distancia)} ${formaRu(g.distancia, "миля", "мили", "миль")}` : `${formatearNumero(ctx, g.distancia)} км`;
  return {
    h1: "Калькулятор стоимости содержания автомобиля",
    title: tituloQueEntre(`Стоимость содержания авто: ${ctx.nombrePais}`, "Калькулятор стоимости содержания авто", "Содержание автомобиля"),
    description: `Рассчитайте, во сколько вам на самом деле обходится машина в месяц, в год и ${imperial ? "за каждую милю" : "за каждый километр"}: топливо, страховка, обслуживание и потеря стоимости.`,
    intro: [
      "Большинство водителей знают, сколько тратят на бензин. Мало кто складывает страховку, обслуживание, парковку и, главное, стоимость, которую машина теряет каждый год.",
      "Введите свои расходы, и мы покажем реальную стоимость владения автомобилем. Это поможет решить, покупать ли машину, менять ли ее или ездить иначе.",
    ],
    comoSeCalcula: [
      imperial
        ? "Топливо в месяц = пробег в милях ÷ миль на галлон × цена галлона."
        : "Топливо в месяц = пробег в км × расход на 100 км ÷ 100 × цена литра.",
      "Потеря стоимости в месяц = стоимость автомобиля × годовая потеря ÷ 12.",
      "Реальная стоимость = топливо + страховка + обслуживание + парковка + прочие расходы + потеря стоимости.",
      `Стоимость одного ${unidad} = реальная стоимость в месяц ÷ пробег за месяц.`,
    ],
    ejemplo: [
      `Автомобиль стоимостью ${m(g.precio)} с пробегом ${distancia} в месяц обходится в ${m(mensual)} в месяц с учетом потери стоимости.`,
      `Это ${m(mensual * 12)} в год и ${formatearMonto(ctx, mensual / g.distancia)} ${imperial ? "за каждую милю" : "за каждый километр"}.`,
    ],
    faq: [
      {
        pregunta: "Что такое амортизация автомобиля?",
        respuesta: "Так называют стоимость, которую машина теряет со временем. Ее не платят каждый месяц, но она ощущается при продаже. У нового автомобиля это часто самая большая статья расходов.",
      },
      {
        pregunta: "Почему не учитывается платеж по автокредиту?",
        respuesta:
          "Часть платежа оплачивает саму машину, а она уже учтена как потеря стоимости. Если сложить оба, автомобиль будет посчитан дважды. Проценты по кредиту добавляются к расходам сверху.",
      },
      {
        pregunta: "Как снизить расходы на содержание машины?",
        respuesta:
          "Каждый год сравнивайте предложения по страховке, следите за давлением в шинах и вовремя проходите обслуживание. И не меняйте машину слишком часто: больше всего она дешевеет в первые годы.",
      },
    ],
    glosario: [
      { termino: "Амортизация", definicion: "Потеря стоимости автомобиля со временем и с пробегом." },
      { termino: `Стоимость одного ${unidad}`, definicion: "Средние расходы на каждый пройденный отрезок пути со всеми затратами." },
    ],
  };
