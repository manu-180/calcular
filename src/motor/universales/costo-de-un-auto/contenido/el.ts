import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { costoMensual, type GastosAuto } from "../definicion";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const g: GastosAuto = {
    precio: montoEjemplo(ctx, 25000),
    depreciacion: 15,
    seguro: montoEjemplo(ctx, 100),
    distancia: 1000,
    consumo: imperial ? 28 : 8,
    precioCombustible: montoEjemplo(ctx, imperial ? 3.5 : 1.2),
    mantenimiento: montoEjemplo(ctx, 60),
    estacionamiento: 0,
    otros: 0,
  };
  const mensual = costoMensual(g, imperial);
  const ana = imperial ? "ανά μίλι" : "ανά χιλιόμετρο";
  return {
    h1: "Υπολογισμός κόστους αυτοκινήτου",
    title: tituloQueEntre(
      `Πόσο κοστίζει ένα αυτοκίνητο ${GRAMATICA.el.en(ctx.nombrePais)}`,
      `Κόστος αυτοκινήτου ${GRAMATICA.el.en(ctx.nombrePais)}`,
      "Υπολογισμός κόστους αυτοκινήτου",
    ),
    description: "Υπολογίστε πόσο σας κοστίζει πραγματικά το αυτοκίνητο τον μήνα, τον χρόνο και ανά χιλιόμετρο: καύσιμα, ασφάλεια, συντήρηση και απώλεια αξίας.",
    intro: [
      "Οι περισσότεροι οδηγοί ξέρουν πόσα δίνουν για καύσιμα. Λίγοι όμως προσθέτουν την ασφάλεια, τη συντήρηση, τη στάθμευση και κυρίως την αξία που χάνει το αυτοκίνητο κάθε χρόνο.",
      "Εισάγετε τα έξοδά σας και θα δείτε πόσο σας κοστίζει πραγματικά. Σας βοηθά να αποφασίσετε αν θα αγοράσετε, αν θα αλλάξετε αυτοκίνητο ή αν θα μετακινείστε αλλιώς.",
    ],
    comoSeCalcula: [
      imperial
        ? "Καύσιμα τον μήνα = μίλια τον μήνα ÷ μίλια ανά γαλόνι × τιμή ανά γαλόνι."
        : "Καύσιμα τον μήνα = χιλιόμετρα τον μήνα × λίτρα ανά 100 km ÷ 100 × τιμή ανά λίτρο.",
      "Απώλεια αξίας τον μήνα = αξία του αυτοκινήτου × ετήσια απώλεια ÷ 12.",
      "Πραγματικό κόστος = καύσιμα + ασφάλεια + συντήρηση + στάθμευση + άλλα έξοδα + απώλεια αξίας.",
      `Κόστος ${ana} = πραγματικό κόστος τον μήνα ÷ απόσταση τον μήνα.`,
    ],
    ejemplo: [
      `Ένα αυτοκίνητο αξίας ${m(g.precio)} που κάνει ${formatearNumero(ctx, g.distancia)} ${imperial ? "μίλια" : "km"} τον μήνα σας κοστίζει ${m(mensual)} τον μήνα μαζί με την απώλεια αξίας.`,
      `Αυτό σημαίνει ${m(mensual * 12)} τον χρόνο και ${formatearMonto(ctx, mensual / g.distancia)} ${ana}.`,
    ],
    faq: [
      {
        pregunta: "Τι είναι η απόσβεση του αυτοκινήτου;",
        respuesta: "Είναι η αξία που χάνει το αυτοκίνητο με τον χρόνο. Δεν την πληρώνετε κάθε μήνα, αλλά τη βλέπετε όταν το πουλάτε. Σε ένα καινούργιο αυτοκίνητο είναι συνήθως το μεγαλύτερο κόστος.",
      },
      {
        pregunta: "Γιατί δεν μετράει η δόση του δανείου;",
        respuesta:
          "Ένα μέρος της δόσης πληρώνει το ίδιο το αυτοκίνητο, που έχει ήδη υπολογιστεί ως απώλεια αξίας. Αν προστίθεντο και τα δύο, το αυτοκίνητο θα μετρούσε δύο φορές. Οι τόκοι του δανείου είναι επιπλέον έξοδο.",
      },
      {
        pregunta: "Πώς μειώνω το κόστος του αυτοκινήτου;",
        respuesta:
          "Συγκρίνετε κάθε χρόνο προσφορές ασφάλειας, ελέγχετε την πίεση των ελαστικών, κάνετε το σέρβις στην ώρα του και μην αλλάζετε αυτοκίνητο πολύ συχνά: τη μεγαλύτερη αξία τη χάνει τα πρώτα χρόνια.",
      },
    ],
    glosario: [
      { termino: "Απόσβεση", definicion: "Η αξία που χάνει το αυτοκίνητο με τον χρόνο και τη χρήση." },
      { termino: `Κόστος ${ana}`, definicion: "Το μέσο κόστος για κάθε μονάδα απόστασης, με όλα τα έξοδα μαζί." },
    ],
  };
};
