import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { area, FT2_POR_M2 } from "../definicion";

export const contenidoAr: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const u = imperial ? "قدم" : "م";
  const us = imperial ? "قدم²" : "م²";
  const enL = imperial ? area("rectangulo", 16, 12) + area("rectangulo", 10, 6) : area("rectangulo", 5, 4) + area("rectangulo", 3, 2);
  return {
    h1: imperial ? "حاسبة المساحة بالقدم المربع" : "حاسبة المساحة بالمتر المربع",
    title: imperial
      ? tituloQueEntre(`حاسبة المساحة بالقدم المربع في ${ctx.nombrePais}`, "حاسبة المساحة بالقدم المربع")
      : tituloQueEntre(`حاسبة المساحة بالمتر المربع في ${ctx.nombrePais}`, "حاسبة المساحة بالمتر المربع"),
    description: "احسب مساحة غرفة أو أرضية أو قطعة أرض: مستطيلات ومثلثات ودوائر، مع جمع ما يصل إلى خمسة أشكال معًا.",
    intro: [
      "اختر الشكل وأدخل قياساته. وإذا لم يكن المكان مستطيلًا بسيطًا، فقسّمه إلى أجزاء وتجمعها الحاسبة لك.",
      imperial ? "وتعرض النتيجة أيضًا بالمتر المربع." : "وتعرض النتيجة أيضًا بالقدم المربع.",
    ],
    comoSeCalcula: [
      "المستطيل: الطول × العرض.",
      "المثلث: القاعدة × الارتفاع ÷ 2.",
      `الدائرة: π × نصف القطر × نصف القطر، ونصف القطر هو نصف طول القطر. والمتر المربع الواحد يساوي ${n(FT2_POR_M2)} قدم².`,
    ],
    ejemplo: [
      imperial
        ? `صالة على شكل حرف L يمكن تقسيمها إلى مستطيل 16 × 12 قدمًا ومستطيل 10 × 6 أقدام. فتكون المساحة الإجمالية ${n(enL, 0)} قدم².`
        : `صالة على شكل حرف L يمكن تقسيمها إلى مستطيل 5 × 4 م ومستطيل 3 × 2 م. فتكون المساحة الإجمالية ${n(enL, 0)} م².`,
      `طاولة مستديرة قطرها 2 ${u} تشغل ${n(area("circulo", 2, 0))} ${us}.`,
    ],
    faq: [
      {
        pregunta: imperial ? "كيف أحسب مساحة غرفة بالقدم المربع؟" : "كيف أحسب مساحة غرفة؟",
        respuesta: imperial
          ? "قِس الطول والعرض بالقدم واضربهما. غرفة 12 × 10 أقدام مساحتها 120 قدم²."
          : "قِس الطول والعرض بالمتر واضربهما. غرفة 4 × 3 م مساحتها 12 م².",
      },
      {
        pregunta: "ماذا لو كانت قياساتي بالبوصة أو بالسنتيمتر؟",
        respuesta: `حوّلها أولًا: اقسم البوصات على 12 لتحصل على الأقدام، أو السنتيمترات على 100 لتحصل على الأمتار. و350 سم تساوي ${n(3.5, 1)} م.`,
      },
      {
        pregunta: "كيف أحوّل المتر المربع إلى قدم مربع؟",
        respuesta: `اضرب في ${n(FT2_POR_M2)}. و20 م² تساوي ${n(20 * FT2_POR_M2)} قدم².`,
      },
    ],
    glosario: [
      { termino: "المتر المربع (م²)", definicion: "مساحة مربع طول ضلعه متر واحد." },
      { termino: "القدم المربع (قدم²)", definicion: "مساحة مربع طول ضلعه قدم واحد." },
    ],
  };
};
