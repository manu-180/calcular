import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { area, FT2_POR_M2 } from "../definicion";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const u = imperial ? "ft" : "м";
  const us = imperial ? "ft²" : "м²";
  const enL = imperial ? area("rectangulo", 16, 12) + area("rectangulo", 10, 6) : area("rectangulo", 5, 4) + area("rectangulo", 3, 2);
  return {
    h1: imperial ? "Калькулятор площі у квадратних футах" : "Калькулятор площі в квадратних метрах",
    title: imperial
      ? tituloQueEntre(`Калькулятор площі (ft²): ${ctx.nombrePais}`, "Калькулятор площі у квадратних футах", "Калькулятор площі")
      : tituloQueEntre(`Калькулятор площі (м²): ${ctx.nombrePais}`, "Калькулятор площі кімнати і ділянки (м²)", "Калькулятор площі"),
    description: "Розрахуйте площу кімнати, підлоги чи ділянки: прямокутник, трикутник і коло, з можливістю додати до пʼяти фігур разом.",
    intro: [
      "Оберіть фігуру і введіть її розміри. Якщо приміщення не є простим прямокутником, поділіть його на частини, і калькулятор їх додасть.",
      imperial ? "Результат показано також у квадратних метрах." : "Результат показано також у квадратних футах.",
    ],
    comoSeCalcula: [
      "Прямокутник: довжина × ширина.",
      "Трикутник: основа × висота ÷ 2.",
      `Коло: π × радіус × радіус; радіус дорівнює половині діаметра. 1 м² = ${n(FT2_POR_M2)} ft².`,
    ],
    ejemplo: [
      imperial
        ? `Г-подібну вітальню можна поділити на два прямокутники 16 × 12 ft і 10 × 6 ft. Загальна площа: ${n(enL, 0)} ft².`
        : `Г-подібну вітальню можна поділити на два прямокутники 5 × 4 м і 3 × 2 м. Загальна площа: ${n(enL, 0)} м².`,
      `Круглий стіл діаметром 2 ${u} займає ${n(area("circulo", 2, 0))} ${us}.`,
    ],
    faq: [
      {
        pregunta: imperial ? "Як розрахувати площу кімнати у квадратних футах?" : "Як розрахувати площу кімнати в квадратних метрах?",
        respuesta: imperial
          ? "Виміряйте довжину і ширину у футах і перемножте їх. Кімната 12 × 10 ft має площу 120 ft²."
          : "Виміряйте довжину і ширину в метрах і перемножте їх. Кімната 4 × 3 м має площу 12 м².",
      },
      {
        pregunta: "Що робити, якщо розміри в сантиметрах чи дюймах?",
        respuesta: `Спершу переведіть їх: поділіть сантиметри на 100, щоб отримати метри, а дюйми на 12, щоб отримати фути. 350 см дорівнюють ${n(3.5, 1)} м.`,
      },
      {
        pregunta: "Як перевести квадратні метри у квадратні фути?",
        respuesta: `Помножте на ${n(FT2_POR_M2)}. 20 м² дорівнюють ${n(20 * FT2_POR_M2)} ft².`,
      },
    ],
    glosario: [
      { termino: "Квадратний метр (м²)", definicion: "Площа квадрата зі стороною 1 метр." },
      { termino: "Квадратний фут (ft²)", definicion: "Площа квадрата зі стороною 1 фут." },
    ],
  };
};
