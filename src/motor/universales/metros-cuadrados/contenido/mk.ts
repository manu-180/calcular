import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { area, FT2_POR_M2 } from "../definicion";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const enL = imperial ? area("rectangulo", 16, 12) + area("rectangulo", 10, 6) : area("rectangulo", 5, 4) + area("rectangulo", 3, 2);
  return {
    h1: imperial ? "Калкулатор за површина во квадратни стапки" : "Калкулатор за квадратни метри",
    title: tituloQueEntre(`Калкулатор за квадратни метри: ${ctx.nombrePais}`, "Калкулатор за квадратура", "Калкулатор за површина"),
    description: "Пресметајте површина на просторија, под или парцела: правоаголници, триаголници и кругови, собрани до пет фигури.",
    intro: [
      "Изберете форма и внесете ги мерките. Ако просторијата не е обичен правоаголник, поделете ја на делови и калкулаторот ќе ги собере.",
      imperial ? "Резултатот се прикажува и во квадратни метри." : "Резултатот се прикажува и во квадратни стапки.",
    ],
    comoSeCalcula: [
      "Правоаголник: должина × ширина.",
      "Триаголник: основа × висина ÷ 2.",
      `Круг: π × радиус × радиус, а радиусот е половина од дијаметарот. 1 м² е еднаков на ${n(FT2_POR_M2)} кв. стапки.`,
    ],
    ejemplo: [
      imperial
        ? `Дневна соба во форма на Г може да се подели на правоаголник 16 × 12 стапки и уште еден 10 × 6 стапки. Вкупно тоа се ${n(enL, 0)} кв. стапки.`
        : `Дневна соба во форма на Г може да се подели на правоаголник 5 × 4 м и уште еден 3 × 2 м. Вкупно тоа се ${n(enL, 0)} м².`,
      imperial
        ? `Тркалезна маса со дијаметар од 2 стапки зафаќа ${n(area("circulo", 2, 0))} кв. стапки.`
        : `Тркалезна маса со дијаметар од 2 м зафаќа ${n(area("circulo", 2, 0))} м².`,
    ],
    faq: [
      {
        pregunta: "Како се пресметува квадратурата на просторија?",
        respuesta: imperial
          ? "Измерете ги должината и ширината во стапки и помножете ги. Просторија 12 × 10 стапки има површина од 120 кв. стапки."
          : "Измерете ги должината и ширината во метри и помножете ги. Просторија 4 × 3 м има површина од 12 м².",
      },
      {
        pregunta: "Што да направам ако мерките се во сантиметри или инчи?",
        respuesta: `Прво претворете ги: поделете ги сантиметрите со 100 за да добиете метри или инчите со 12 за да добиете стапки. 350 см се ${n(3.5, 1)} м.`,
      },
      {
        pregunta: "Како се претвораат квадратни метри во квадратни стапки?",
        respuesta: `Помножете со ${n(FT2_POR_M2)}. 20 м² се ${n(20 * FT2_POR_M2)} кв. стапки.`,
      },
    ],
    glosario: [
      { termino: "Квадратен метар (м²)", definicion: "Површината на квадрат со страна од 1 метар." },
      { termino: "Квадратна стапка", definicion: `Површината на квадрат со страна од 1 стапка, околу ${n(1 / FT2_POR_M2)} м².` },
    ],
  };
};
