import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { area, FT2_POR_M2 } from "../definicion";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const enL = imperial ? area("rectangulo", 16, 12) + area("rectangulo", 10, 6) : area("rectangulo", 5, 4) + area("rectangulo", 3, 2);
  return {
    h1: imperial ? "Калкулатор за площ в квадратни футове" : "Калкулатор за квадратни метри",
    title: tituloQueEntre(`Калкулатор за квадратни метри: ${ctx.nombrePais}`, "Калкулатор за квадратура", "Калкулатор за площ"),
    description: "Изчислете площта на стая, под или парцел: правоъгълници, триъгълници и кръгове, като събирате до пет фигури заедно.",
    intro: [
      "Изберете форма и въведете размерите. Ако помещението не е обикновен правоъгълник, разделете го на части и калкулаторът ще ги събере.",
      imperial ? "Резултатът се показва и в квадратни метри." : "Резултатът се показва и в квадратни футове.",
    ],
    comoSeCalcula: [
      "Правоъгълник: дължина × ширина.",
      "Триъгълник: основа × височина ÷ 2.",
      `Кръг: π × радиус × радиус, като радиусът е половината от диаметъра. 1 м² е равен на ${n(FT2_POR_M2)} кв. фута.`,
    ],
    ejemplo: [
      imperial
        ? `Г-образна дневна може да се раздели на правоъгълник 16 × 12 фута и още един 10 × 6 фута. Общо това са ${n(enL, 0)} кв. фута.`
        : `Г-образна дневна може да се раздели на правоъгълник 5 × 4 м и още един 3 × 2 м. Общо това са ${n(enL, 0)} м².`,
      imperial
        ? `Кръгла маса с диаметър 2 фута заема ${n(area("circulo", 2, 0))} кв. фута.`
        : `Кръгла маса с диаметър 2 м заема ${n(area("circulo", 2, 0))} м².`,
    ],
    faq: [
      {
        pregunta: "Как се изчислява квадратурата на стая?",
        respuesta: imperial
          ? "Измерете дължината и ширината във футове и ги умножете. Стая 12 × 10 фута има площ 120 кв. фута."
          : "Измерете дължината и ширината в метри и ги умножете. Стая 4 × 3 м има площ 12 м².",
      },
      {
        pregunta: "Какво да направя, ако мерките са в сантиметри или инчове?",
        respuesta: `Първо ги превърнете: разделете сантиметрите на 100, за да получите метри, или инчовете на 12, за да получите футове. 350 см са ${n(3.5, 1)} м.`,
      },
      {
        pregunta: "Как се превръщат квадратни метри в квадратни футове?",
        respuesta: `Умножете по ${n(FT2_POR_M2)}. 20 м² са ${n(20 * FT2_POR_M2)} кв. фута.`,
      },
    ],
    glosario: [
      { termino: "Квадратен метър (м²)", definicion: "Площта на квадрат със страна 1 метър." },
      { termino: "Квадратен фут", definicion: `Площта на квадрат със страна 1 фут, около ${n(1 / FT2_POR_M2)} м².` },
    ],
  };
};
