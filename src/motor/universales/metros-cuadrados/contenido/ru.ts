import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { area, FT2_POR_M2 } from "../definicion";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const enL = imperial ? area("rectangulo", 16, 12) + area("rectangulo", 10, 6) : area("rectangulo", 5, 4) + area("rectangulo", 3, 2);
  return {
    h1: imperial ? "Калькулятор площади в квадратных футах" : "Калькулятор площади в квадратных метрах",
    title: tituloQueEntre(`Калькулятор площади: ${ctx.nombrePais}`, "Калькулятор площади помещения", "Калькулятор площади"),
    description: "Рассчитайте площадь комнаты, пола или участка: прямоугольники, треугольники и круги, до пяти фигур вместе.",
    intro: [
      "Выберите форму и введите размеры. Если помещение не простой прямоугольник, разделите его на части, и калькулятор их сложит.",
      imperial ? "Результат также показывается в квадратных метрах." : "Результат также показывается в квадратных футах.",
    ],
    comoSeCalcula: [
      "Прямоугольник: длина × ширина.",
      "Треугольник: основание × высота ÷ 2.",
      `Круг: π × радиус × радиус, где радиус равен половине диаметра. 1 м² равен ${n(FT2_POR_M2)} кв. фута.`,
    ],
    ejemplo: [
      imperial
        ? `Г-образную гостиную можно разделить на прямоугольники 16 × 12 футов и 10 × 6 футов. Вместе это ${n(enL, 0)} кв. футов.`
        : `Г-образную гостиную можно разделить на прямоугольники 5 × 4 м и 3 × 2 м. Вместе это ${n(enL, 0)} м².`,
      imperial
        ? `Круглый стол диаметром 2 фута занимает ${n(area("circulo", 2, 0))} кв. фута.`
        : `Круглый стол диаметром 2 м занимает ${n(area("circulo", 2, 0))} м².`,
    ],
    faq: [
      {
        pregunta: "Как посчитать площадь комнаты?",
        respuesta: imperial
          ? "Измерьте длину и ширину в футах и перемножьте их. Комната 12 × 10 футов имеет площадь 120 кв. футов."
          : "Измерьте длину и ширину в метрах и перемножьте их. Комната 4 × 3 м имеет площадь 12 м².",
      },
      {
        pregunta: "Что делать, если размеры в сантиметрах или дюймах?",
        respuesta: `Сначала переведите их: сантиметры разделите на 100, чтобы получить метры, а дюймы на 12, чтобы получить футы. 350 см равны ${n(3.5, 1)} м.`,
      },
      {
        pregunta: "Как перевести квадратные метры в квадратные футы?",
        respuesta: `Умножьте на ${n(FT2_POR_M2)}. 20 м² равны ${n(20 * FT2_POR_M2)} кв. фута.`,
      },
      {
        pregunta: "Как посчитать площадь комнаты сложной формы?",
        respuesta: "Разделите ее на прямоугольники, треугольники или круги, посчитайте каждую часть и сложите результаты. Калькулятор принимает до пяти частей.",
      },
    ],
    glosario: [
      { termino: "Квадратный метр (м²)", definicion: "Площадь квадрата со стороной 1 метр." },
      { termino: "Квадратный фут", definicion: "Площадь квадрата со стороной 1 фут." },
    ],
  };
};
