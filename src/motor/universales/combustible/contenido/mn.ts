import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoMn: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `Нэг галлоноор 30 миль явдаг машинаар 150 миль замыг очиж ирэхэд ${formatearNumero(ctx, galones)} галлон шатахуун хэрэгтэй.`,
          `Нэг галлон ${m(precio)} бол нийт ${m(galones * precio)} болно. Хоёр хүн хуваавал нэг хүнд ${m((galones * precio) / 2)} ногдоно.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `100 km тутамд 8 литр зарцуулдаг машинаар 300 km замыг очиж ирэхэд ${formatearNumero(ctx, litros)} литр шатахуун хэрэгтэй.`,
          `Нэг литр ${m(precio)} бол нийт ${m(litros * precio)} болно. Хоёр хүн хуваавал нэг хүнд ${m((litros * precio) / 2)} ногдоно.`,
        ];
      })();
  return {
    h1: "Шатахууны зардлын тооцоолуур",
    title: tituloQueEntre(`${GRAMATICA.mn.para(ctx.nombrePais)} шатахууны зардлын тооцоолуур`, "Шатахууны зардлын тооцоолуур", "Шатахууны зардал"),
    description: "Замын зай, машины зарцуулалт, шатахууны үнээс хамааран аяллын шатахууны зардал хэд болох, хүн бүр хэдийг төлөхийг тооцоолно уу.",
    intro: [
      `Замын зай, машины зарцуулалт, нэг ${imperial ? "галлоны" : "литрийн"} үнийг оруулна уу. Хэдэн шатахуун хэрэгтэй, аялал хэд болохыг харна.`,
      imperial ? "Зарцуулалтыг машины мэдээлэлд заасны дагуу галлон тутамд милээр оруулна." : "Зарцуулалтыг 100 km тутамд литрээр эсвэл нэг литрээр явах километрээр оруулж болно.",
    ],
    comoSeCalcula: imperial
      ? ["Галлон = зай ÷ галлон тутамд миль.", "Зардал = галлон × нэг галлоны үнэ. Очиж ирэх бол зайг хоёр дахин авна."]
      : [
          "100 km тутамд литрээр: литр = зай × зарцуулалт ÷ 100.",
          "Литр тутамд километрээр: литр = зай ÷ зарцуулалт.",
          "Зардал = литр × нэг литрийн үнэ. Очиж ирэх бол зайг хоёр дахин авна.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "Галлон тутамд милийг 100 km тутамд литр болгож хэрхэн хөрвүүлэх вэ?",
        respuesta: `${formatearNumero(ctx, 235.215, 1)} тоог галлон тутамд явах милийн тоонд хуваана уу (АНУ-ын галлон). Нэг галлоноор 30 миль явдаг машин 100 km тутамд ойролцоогоор ${formatearNumero(ctx, 235.215 / 30, 1)} литр зарцуулна.`,
      },
      {
        pregunta: "Замын хураамж орсон уу?",
        respuesta: "Үгүй. Энэ тооцоо зөвхөн шатахууныг хамарна. Замын хураамж, зогсоолын төлбөрийг тусад нь нэмнэ үү.",
      },
      {
        pregunta: "Машин яагаад хотод илүү зарцуулдаг вэ?",
        respuesta: "Байнга зогсож хөдлөхөд хурдны замаар жигд явахаас илүү энерги шаардагддаг тул хотод зарцуулалт ихэвчлэн өндөр байдаг.",
      },
    ],
    glosario: [
      { termino: "Шатахууны зарцуулалт", definicion: "Тээврийн хэрэгсэл тодорхой зайд хэдий хэмжээний шатахуун зарцуулахыг заана. Бага байх тусам сайн." },
      { termino: "100 km тутамд литр", definicion: "100 километр явахад хэдэн литр шатахуун шаардлагатайг заана." },
    ],
  };
};
