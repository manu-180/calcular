import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoTh: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `การเดินทางไปกลับระยะ 150 ไมล์ ด้วยรถที่วิ่งได้ 30 ไมล์ต่อแกลลอน ใช้น้ำมัน ${formatearNumero(ctx, galones)} แกลลอน`,
          `ที่ราคา ${m(precio)} ต่อแกลลอน คิดเป็น ${m(galones * precio)} หากหารกัน 2 คน จะเป็นคนละ ${m((galones * precio) / 2)}`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `การเดินทางไปกลับระยะ 300 กม. ด้วยรถที่ใช้น้ำมัน 8 ลิตรต่อ 100 กม. ต้องใช้น้ำมัน ${formatearNumero(ctx, litros)} ลิตร`,
          `ที่ราคา ${m(precio)} ต่อลิตร คิดเป็น ${m(litros * precio)} หากหารกัน 2 คน จะเป็นคนละ ${m((litros * precio) / 2)}`,
        ];
      })();
  return {
    h1: "คำนวณค่าน้ำมัน",
    title: tituloQueEntre(`คำนวณค่าน้ำมันเดินทางใน${ctx.nombrePais}`, "คำนวณค่าน้ำมันเดินทาง"),
    description: "คำนวณค่าน้ำมันของการเดินทางจากระยะทาง อัตราสิ้นเปลืองของรถ และราคาน้ำมัน พร้อมดูว่าแต่ละคนต้องจ่ายเท่าไรเมื่อหารกัน",
    intro: [
      `กรอกระยะทาง อัตราสิ้นเปลืองของรถ และราคาน้ำมันต่อ${imperial ? "แกลลอน" : "ลิตร"} แล้วดูว่าต้องใช้น้ำมันเท่าไรและการเดินทางครั้งนี้มีค่าใช้จ่ายเท่าไร`,
      imperial ? "อัตราสิ้นเปลืองใช้หน่วยไมล์ต่อแกลลอน ตามที่ระบุไว้ในข้อมูลรถ" : "อัตราสิ้นเปลืองกรอกได้ทั้งแบบลิตรต่อ 100 กม. และแบบกิโลเมตรต่อลิตร",
    ],
    comoSeCalcula: imperial
      ? ["แกลลอน = ระยะทาง ÷ ไมล์ต่อแกลลอน", "ค่าน้ำมัน = แกลลอน × ราคาต่อแกลลอน หากไปกลับ ระยะทางจะเป็นสองเท่า"]
      : [
          "แบบลิตรต่อ 100 กม.: ลิตร = ระยะทาง × อัตราสิ้นเปลือง ÷ 100",
          "แบบกิโลเมตรต่อลิตร: ลิตร = ระยะทาง ÷ อัตราสิ้นเปลือง",
          "ค่าน้ำมัน = ลิตร × ราคาต่อลิตร หากไปกลับ ระยะทางจะเป็นสองเท่า",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "แปลงกิโลเมตรต่อลิตรเป็นลิตรต่อ 100 กม. อย่างไร",
        respuesta: `นำ 100 หารด้วยกิโลเมตรต่อลิตร รถที่วิ่งได้ 15 กม./ลิตร ใช้น้ำมันประมาณ ${formatearNumero(ctx, 100 / 15, 1)} ลิตรต่อ 100 กม. ส่วนไมล์ต่อแกลลอน (แกลลอนสหรัฐ) ให้นำ ${formatearNumero(ctx, 235.215, 1)} หารด้วยค่านั้น`,
      },
      {
        pregunta: "รวมค่าทางด่วนหรือไม่",
        respuesta: "ไม่รวม เครื่องคำนวณนี้คิดเฉพาะค่าน้ำมัน ค่าทางด่วนและค่าที่จอดรถให้บวกแยกต่างหาก",
      },
      {
        pregunta: "ทำไมขับในเมืองจึงเปลืองน้ำมันกว่า",
        respuesta: "การหยุดและออกตัวบ่อยใช้พลังงานมากกว่าการขับด้วยความเร็วคงที่บนทางหลวง อัตราสิ้นเปลืองในเมืองจึงมักสูงกว่า",
      },
    ],
    glosario: [
      { termino: "อัตราสิ้นเปลือง", definicion: "ระยะทางที่รถวิ่งได้ต่อปริมาณน้ำมันที่กำหนด หรือปริมาณน้ำมันที่ใช้ต่อระยะทาง" },
      { termino: "กม./ลิตร", definicion: "กิโลเมตรต่อลิตร ยิ่งตัวเลขสูง ยิ่งประหยัดน้ำมัน" },
    ],
  };
};
