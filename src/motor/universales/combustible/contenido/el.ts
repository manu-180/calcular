import { formaEl } from "../../../i18n/plural";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const litra = (x: number) => formaEl(x, "λίτρο", "λίτρα");
  const galonia = (x: number) => formaEl(x, "γαλόνι", "γαλόνια");
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `Για διαδρομή 150 μιλίων με επιστροφή, ένα αυτοκίνητο που κάνει 30 μίλια το γαλόνι χρειάζεται ${formatearNumero(ctx, galones)} ${galonia(galones)} καυσίμου.`,
          `Με τιμή ${m(precio)} το γαλόνι, το κόστος είναι ${m(galones * precio)}. Αν το μοιραστούν 2 άτομα, ο καθένας πληρώνει ${m((galones * precio) / 2)}.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `Για διαδρομή 300 km με επιστροφή, ένα αυτοκίνητο με κατανάλωση 8 λίτρα στα 100 km χρειάζεται ${formatearNumero(ctx, litros)} ${litra(litros)} καυσίμου.`,
          `Με τιμή ${m(precio)} το λίτρο, το κόστος είναι ${m(litros * precio)}. Αν το μοιραστούν 2 άτομα, ο καθένας πληρώνει ${m((litros * precio) / 2)}.`,
        ];
      })();
  const prevod = Math.round((235.215 / 30) * 10) / 10;
  return {
    h1: "Υπολογισμός κατανάλωσης καυσίμου",
    title: tituloQueEntre(
      `Υπολογισμός κατανάλωσης καυσίμου (${ctx.nombrePais})`,
      "Κατανάλωση καυσίμου και κόστος διαδρομής",
      "Υπολογισμός κατανάλωσης καυσίμου",
    ),
    description: "Υπολογίστε πόσο καύσιμο θα χρειαστείτε για μια διαδρομή και πόσο θα σας κοστίσει, με βάση την απόσταση, την κατανάλωση και την τιμή.",
    intro: [
      `Εισάγετε την απόσταση, την κατανάλωση του αυτοκινήτου σας και την τιμή ανά ${imperial ? "γαλόνι" : "λίτρο"}. Θα δείτε πόσο καύσιμο χρειάζεστε και πόσο κοστίζει η διαδρομή.`,
      imperial ? "Η κατανάλωση δίνεται σε μίλια ανά γαλόνι." : "Μπορείτε να εισαγάγετε την κατανάλωση σε λίτρα ανά 100 km ή σε χιλιόμετρα ανά λίτρο.",
    ],
    comoSeCalcula: imperial
      ? ["Γαλόνια = απόσταση ÷ μίλια ανά γαλόνι.", "Κόστος = γαλόνια × τιμή ανά γαλόνι. Αν επιλέξετε «Με επιστροφή», η απόσταση διπλασιάζεται."]
      : [
          "Σε λίτρα ανά 100 km: λίτρα = απόσταση × κατανάλωση ÷ 100.",
          "Σε χιλιόμετρα ανά λίτρο: λίτρα = απόσταση ÷ κατανάλωση.",
          "Κόστος = λίτρα × τιμή ανά λίτρο. Αν επιλέξετε «Με επιστροφή», η απόσταση διπλασιάζεται.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "Πώς μετατρέπω τα μίλια ανά γαλόνι σε λίτρα ανά 100 km;",
        respuesta: `Διαιρέστε το ${formatearNumero(ctx, 235.215, 1)} με την τιμή mpg (αμερικανικό γαλόνι). Ένα αυτοκίνητο που κάνει 30 μίλια το γαλόνι καταναλώνει περίπου ${formatearNumero(ctx, prevod, 1)} ${litra(prevod)} στα 100 km.`,
      },
      {
        pregunta: "Περιλαμβάνονται τα διόδια;",
        respuesta: "Όχι. Υπολογίζεται μόνο το καύσιμο. Διόδια, στάθμευση και πλοία προσθέστε τα χωριστά.",
      },
      {
        pregunta: "Γιατί στην πόλη το αυτοκίνητο καίει περισσότερο;",
        respuesta: "Τα συχνά σταματήματα και ξεκινήματα θέλουν περισσότερη ενέργεια από την οδήγηση με σταθερή ταχύτητα στον αυτοκινητόδρομο. Γι' αυτό η κατανάλωση στην πόλη είναι συνήθως μεγαλύτερη.",
      },
    ],
    glosario: [
      { termino: "Κατανάλωση καυσίμου", definicion: "Πόσο καύσιμο καίει το αυτοκίνητο σε μια απόσταση ή πόση απόσταση κάνει με μια ποσότητα καυσίμου." },
      { termino: "mpg", definicion: "Μίλια ανά γαλόνι. Όσο μεγαλύτερη η τιμή, τόσο πιο οικονομικό το αυτοκίνητο." },
    ],
  };
};
