import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `Поездка на 150 миль туда и обратно на машине с расходом 30 миль на галлон потребует ${formatearNumero(ctx, galones)} галлонов.`,
          `При цене ${m(precio)} за галлон это ${m(galones * precio)}. Если разделить на двоих, каждый заплатит ${m((galones * precio) / 2)}.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `Поездка на 300 км туда и обратно на машине с расходом 8 литров на 100 км потребует ${formatearNumero(ctx, litros)} литров.`,
          `При цене ${m(precio)} за литр это ${m(litros * precio)}. Если разделить на двоих, каждый заплатит ${m((litros * precio) / 2)}.`,
        ];
      })();
  return {
    h1: "Калькулятор расхода топлива",
    title: tituloQueEntre(`Калькулятор расхода топлива: ${ctx.nombrePais}`, "Калькулятор расхода топлива", "Расход топлива"),
    description: "Рассчитайте, сколько стоит бензин на поездку, по расстоянию, расходу машины и цене топлива, и сколько платит каждый попутчик.",
    intro: [
      `Введите расстояние, расход топлива и цену за ${imperial ? "галлон" : "литр"}. Калькулятор покажет, сколько топлива понадобится и во что обойдется поездка.`,
      imperial ? "Расход указывается в милях на галлон, как в документах на машину." : "Расход можно указать в литрах на 100 км или в километрах на литр.",
    ],
    comoSeCalcula: imperial
      ? ["Галлоны = расстояние ÷ мили на галлон.", "Стоимость = галлоны × цена за галлон. Поездка туда и обратно удваивает расстояние."]
      : [
          "При расходе в литрах на 100 км: литры = расстояние × расход ÷ 100.",
          "При расходе в километрах на литр: литры = расстояние ÷ расход.",
          "Стоимость = литры × цена за литр. Поездка туда и обратно удваивает расстояние.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "Как рассчитать расход бензина на поездку?",
        respuesta: "Умножьте расстояние на расход в литрах на 100 км и разделите на 100. Полученные литры умножьте на цену за литр.",
      },
      {
        pregunta: "Как перевести мили на галлон в литры на 100 км?",
        respuesta: `Разделите ${formatearNumero(ctx, 235.215, 1)} на число миль на галлон (американский галлон). Машина с расходом 30 миль на галлон тратит около ${formatearNumero(ctx, 235.215 / 30, 1)} литра на 100 км.`,
      },
      {
        pregunta: "Учитываются ли платные дороги?",
        respuesta: "Нет. Калькулятор считает только топливо. Платные дороги и парковку добавьте отдельно.",
      },
      {
        pregunta: "Почему в городе расход больше?",
        respuesta: "Частые остановки и разгоны требуют больше энергии, чем ровная езда по трассе, поэтому городской расход обычно выше.",
      },
    ],
    glosario: [
      { termino: "Расход топлива", definicion: "Сколько топлива машина тратит на определенное расстояние." },
      { termino: "л/100 км", definicion: "Литров на 100 километров. Чем меньше, тем экономичнее машина." },
    ],
  };
};
