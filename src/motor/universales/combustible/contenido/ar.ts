import { contenidoArabe } from "../../comun/arabe";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoAr: ContenidoUniversal = contenidoArabe((ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `رحلة ذهاب وعودة مسافتها 150 ميلًا في كل اتجاه، بسيارة تقطع 30 ميلًا بالغالون، تستهلك ${formatearNumero(ctx, galones)} غالونات.`,
          `بسعر ${m(precio)} للغالون تكون التكلفة ${m(galones * precio)}. وإذا تقاسمها شخصان يدفع كل منهما ${m((galones * precio) / 2)}.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `رحلة ذهاب وعودة مسافتها 300 كم في كل اتجاه، بسيارة تستهلك 8 لترات لكل 100 كم، تحتاج إلى ${formatearNumero(ctx, litros)} لترًا.`,
          `بسعر ${m(precio)} للتر تكون التكلفة ${m(litros * precio)}. وإذا تقاسمها شخصان يدفع كل منهما ${m((litros * precio) / 2)}.`,
        ];
      })();
  return {
    h1: "حاسبة تكلفة الوقود",
    title: tituloQueEntre(`حاسبة تكلفة الوقود في ${ctx.nombrePais}`, "حاسبة تكلفة الوقود للرحلة", "حاسبة تكلفة الوقود"),
    description: "احسب تكلفة الوقود لرحلتك من المسافة واستهلاك سيارتك وسعر الوقود، واعرف نصيب كل شخص من التكلفة.",
    intro: [
      `أدخل المسافة واستهلاك سيارتك للوقود وسعر ${imperial ? "الغالون" : "اللتر"}، فتعرف كمية الوقود التي تحتاجها وتكلفة الرحلة.`,
      imperial ? "يُدخل الاستهلاك بالميل لكل غالون، كما يظهر في بيانات السيارة." : "يمكن إدخال الاستهلاك باللتر لكل 100 كم أو بالكيلومتر لكل لتر.",
    ],
    comoSeCalcula: imperial
      ? ["عدد الغالونات = المسافة ÷ عدد الأميال لكل غالون.", "التكلفة = عدد الغالونات × سعر الغالون. ورحلة الذهاب والعودة تضاعف المسافة."]
      : [
          "مع اللتر لكل 100 كم: عدد اللترات = المسافة × الاستهلاك ÷ 100.",
          "مع الكيلومتر لكل لتر: عدد اللترات = المسافة ÷ الاستهلاك.",
          "التكلفة = عدد اللترات × سعر اللتر. ورحلة الذهاب والعودة تضاعف المسافة.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "كيف أحوّل الميل لكل غالون إلى لتر لكل 100 كم؟",
        respuesta: `اقسم ${formatearNumero(ctx, 235.215, 1)} على عدد الأميال لكل غالون (الغالون الأمريكي). السيارة التي تقطع 30 ميلًا بالغالون تستهلك نحو ${formatearNumero(ctx, 235.215 / 30, 1)} لتر لكل 100 كم.`,
      },
      {
        pregunta: "هل تشمل الحاسبة رسوم الطرق؟",
        respuesta: "لا. فهي تحسب الوقود فقط. أضف رسوم الطرق والمواقف على حدة.",
      },
      {
        pregunta: "لماذا تستهلك سيارتي وقودًا أكثر في المدينة؟",
        respuesta: "لأن التوقف والانطلاق المتكرر يحتاج إلى طاقة أكثر من القيادة بسرعة ثابتة على الطريق السريع، لذلك يكون الاستهلاك في المدينة أعلى عادة.",
      },
    ],
    glosario: [
      { termino: "استهلاك الوقود", definicion: "المسافة التي تقطعها السيارة بكمية معينة من الوقود، أو كمية الوقود لكل 100 كم." },
      { termino: "ميل لكل غالون (mpg)", definicion: "عدد الأميال التي تقطعها السيارة بغالون واحد. وكلما ارتفع كان أفضل." },
    ],
  };
});
