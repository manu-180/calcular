import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `Патување од 150 милји во секој правец со автомобил што минува 30 милји со галон бара ${formatearNumero(ctx, galones)} галони.`,
          `По ${m(precio)} за галон, тоа се ${m(galones * precio)} за целиот пат. Поделено меѓу две лица, по ${m((galones * precio) / 2)} по лице.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `Патување од 300 km во секој правец со автомобил што троши 8 литри на 100 km бара ${formatearNumero(ctx, litros)} литри.`,
          `По ${m(precio)} за литар, тоа се ${m(litros * precio)} за целиот пат. Поделено меѓу две лица, по ${m((litros * precio) / 2)} по лице.`,
        ];
      })();
  return {
    h1: "Калкулатор за потрошувачка на гориво",
    title: tituloQueEntre(`Потрошувачка на гориво ${GRAMATICA.mk.en(ctx.nombrePais)}`, "Потрошувачка на гориво", "Трошок за гориво"),
    description: "Пресметајте колку чини горивото за патување според растојанието, потрошувачката и цената на горивото и колку плаќа секој.",
    intro: [
      `Внесете го растојанието, потрошувачката на автомобилот и цената на ${imperial ? "галон" : "литар"}. Ќе видите колку гориво ви треба и колку чини патувањето.`,
      imperial ? "Потрошувачката се внесува во милји на галон, како во податоците за автомобилот." : "Потрошувачката може да се внесе во литри на 100 km или во километри со еден литар.",
    ],
    comoSeCalcula: imperial
      ? ["Галони = растојание ÷ милји на галон.", "Цена = галони × цена на галон. При патување во двата правца растојанието се удвојува."]
      : [
          "Со литри на 100 km: литри = растојание × потрошувачка ÷ 100.",
          "Со километри на литар: литри = растојание ÷ потрошувачка.",
          "Цена = литри × цена на литар. При патување во двата правца растојанието се удвојува.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "Како да претворам милји на галон во литри на 100 km?",
        respuesta: `Поделете го ${formatearNumero(ctx, 235.215, 1)} со милјите на галон (американски галон). Автомобил што минува 30 милји со галон троши околу ${formatearNumero(ctx, 235.215 / 30, 1)} литри на 100 km.`,
      },
      {
        pregunta: "Дали се вклучени патарините?",
        respuesta: "Не. Пресметката е само за горивото. Патарините и паркирањето додајте ги посебно.",
      },
      {
        pregunta: "Зошто автомобилот троши повеќе во град?",
        respuesta: "Честото запирање и тргнување бара повеќе енергија од рамномерното возење на автопат, затоа потрошувачката во град обично е повисока.",
      },
    ],
    glosario: [
      { termino: "Потрошувачка на гориво", definicion: "Колку гориво троши возилото за дадено растојание. Колку е пониска, толку подобро." },
      { termino: "Литри на 100 km", definicion: "Колку литри гориво се потребни за 100 километри." },
    ],
  };
};
