import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `Пътуване от 150 мили в двете посоки с кола, която минава 30 мили с галон, изисква ${formatearNumero(ctx, galones)} галона.`,
          `При ${m(precio)} за галон това прави ${m(galones * precio)}. Разделено между двама души, по ${m((galones * precio) / 2)} на човек.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `Пътуване от 300 km в едната посока и обратно с кола, която харчи 8 литра на 100 km, изисква ${formatearNumero(ctx, litros)} литра.`,
          `При ${m(precio)} за литър това прави ${m(litros * precio)}. Разделено между двама души, по ${m((litros * precio) / 2)} на човек.`,
        ];
      })();
  return {
    h1: "Калкулатор за разход на гориво",
    title: tituloQueEntre(`Калкулатор за разход на гориво ${GRAMATICA.bg.en(ctx.nombrePais)}`, "Калкулатор за разход на гориво", "Разход на гориво"),
    description: "Изчислете колко струва горивото за едно пътуване според разстоянието, разхода на колата и цената на горивото и колко плаща всеки.",
    intro: [
      `Въведете разстоянието, разхода на автомобила и цената на ${imperial ? "галон" : "литър"}. Ще видите колко гориво Ви трябва и колко струва пътуването.`,
      imperial ? "Разходът се въвежда в мили на галон, както е в данните на колата." : "Разходът може да се въведе в литри на 100 km или в километри с един литър.",
    ],
    comoSeCalcula: imperial
      ? ["Галони = разстояние ÷ мили на галон.", "Цена = галони × цена на галон. При отиване и връщане разстоянието се удвоява."]
      : [
          "С литри на 100 km: литри = разстояние × разход ÷ 100.",
          "С километри на литър: литри = разстояние ÷ разход.",
          "Цена = литри × цена на литър. При отиване и връщане разстоянието се удвоява.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "Как да превърна мили на галон в литри на 100 km?",
        respuesta: `Разделете ${formatearNumero(ctx, 235.215, 1)} на милите с галон (американски галон). Кола, която минава 30 мили с галон, харчи около ${formatearNumero(ctx, 235.215 / 30, 1)} литра на 100 km.`,
      },
      {
        pregunta: "Включени ли са тол таксите и винетката?",
        respuesta: "Не. Изчислението е само за горивото. Добавете тол таксите и паркирането отделно.",
      },
      {
        pregunta: "Защо колата харчи повече в града?",
        respuesta: "Честото спиране и потегляне изисква повече енергия от равномерното каране по магистрала, затова разходът в града обикновено е по-висок.",
      },
    ],
    glosario: [
      { termino: "Разход на гориво", definicion: "Колко гориво харчи превозното средство за дадено разстояние. Колкото е по-нисък, толкова по-добре." },
      { termino: "Литри на 100 km", definicion: "Колко литра гориво са нужни за 100 километра." },
    ],
  };
};
