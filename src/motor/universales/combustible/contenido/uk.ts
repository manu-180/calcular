import { formatearMonto, formatearNumero, montoEjemplo, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const m = (n: number) => formatearMonto(ctx, n);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const precio = montoEjemplo(ctx, 3.5);
        const galones = 300 / 30;
        return [
          `Для поїздки на 150 миль туди й назад авто, яке проїжджає 30 миль на галон, потребує ${formatearNumero(ctx, galones)} галонів пального.`,
          `За ціни ${m(precio)} за галон це коштуватиме ${m(galones * precio)}. Якщо поділити на 2 людей, кожен заплатить ${m((galones * precio) / 2)}.`,
        ];
      })()
    : (() => {
        const precio = montoEjemplo(ctx, 1.2);
        const litros = (600 * 8) / 100;
        return [
          `Для поїздки на 300 км туди й назад авто з витратою 8 літрів на 100 км потребує ${formatearNumero(ctx, litros)} літрів пального.`,
          `За ціни ${m(precio)} за літр це коштуватиме ${m(litros * precio)}. Якщо поділити на 2 людей, кожен заплатить ${m((litros * precio) / 2)}.`,
        ];
      })();
  return {
    h1: "Калькулятор витрати пального",
    title: tituloQueEntre(
      `Калькулятор витрати пального: ${ctx.nombrePais}`,
      "Калькулятор витрати пального і вартості поїздки",
      "Калькулятор витрати пального",
    ),
    description: "Розрахуйте, скільки пального потрібно на поїздку і скільки вона коштуватиме, за відстанню, витратою авто і ціною пального.",
    intro: [
      `Введіть відстань, витрату пального вашого авто і ціну ${imperial ? "галона" : "літра"}. Ви побачите, скільки пального потрібно і скільки коштуватиме поїздка.`,
      imperial ? "Витрату вказують у милях на галон." : "Витрату можна ввести в літрах на 100 км або в кілометрах на літр.",
    ],
    comoSeCalcula: imperial
      ? ["Галони = відстань ÷ милі на галон.", "Вартість = галони × ціна галона. Якщо обрати «Туди й назад», відстань подвоюється."]
      : [
          "У літрах на 100 км: літри = відстань × витрата ÷ 100.",
          "У кілометрах на літр: літри = відстань ÷ витрата.",
          "Вартість = літри × ціна літра. Якщо обрати «Туди й назад», відстань подвоюється.",
        ],
    ejemplo,
    faq: [
      {
        pregunta: "Як перевести милі на галон у літри на 100 км?",
        respuesta: `Поділіть ${formatearNumero(ctx, 235.215, 1)} на значення mpg (американський галон). Авто, яке проїжджає 30 миль на галон, витрачає близько ${formatearNumero(ctx, 235.215 / 30, 1)} літра на 100 км.`,
      },
      {
        pregunta: "Чи враховано платні дороги?",
        respuesta: "Ні. Рахується лише пальне. Плату за дороги і паркування додайте окремо.",
      },
      {
        pregunta: "Чому в місті авто витрачає більше?",
        respuesta: "Рух із постійними зупинками потребує більше енергії, ніж їзда на трасі зі сталою швидкістю. Тому міська витрата зазвичай вища.",
      },
    ],
    glosario: [
      { termino: "Витрата пального", definicion: "Скільки пального авто витрачає на певну відстань або скільки проїжджає на певній кількості пального." },
      { termino: "mpg", definicion: "Миль на галон. Що більше значення, то економніше авто." },
    ],
  };
};
