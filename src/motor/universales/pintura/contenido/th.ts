import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoTh: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `ห้องที่ผนังยาวรวม 48 ฟุต สูง 8 ฟุต และมีประตูกับหน้าต่างรวม 40 ตร.ฟุต มีพื้นที่ที่จะทาสี ${n(neta, 0)} ตร.ฟุต`,
          `หากทา 2 รอบด้วยสีที่ทาได้ 350 ตร.ฟุตต่อแกลลอน จะใช้สี ${n(gal, 2)} แกลลอน และเมื่อรวมส่วนเผื่อแล้วเป็น ${n(gal * (1 + MARGEN), 2)} แกลลอน`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `ห้องที่ผนังยาวรวม 14 ม. สูง ${n(2.6)} ม. และมีประตูกับหน้าต่างรวม 4 ตร.ม. มีพื้นที่ที่จะทาสี ${n(neta)} ตร.ม.`,
          `หากทา 2 รอบด้วยสีที่ทาได้ 10 ตร.ม. ต่อลิตร จะใช้สี ${n(litros, 2)} ลิตร และเมื่อรวมส่วนเผื่อแล้วเป็น ${n(litros * (1 + MARGEN), 2)} ลิตร`,
        ];
      })();
  return {
    h1: "คำนวณสีทาบ้าน",
    title: tituloQueEntre(`คำนวณสีทาบ้าน ต้องใช้สีกี่ลิตร | ${ctx.nombrePais}`, "คำนวณสีทาบ้าน ต้องใช้สีกี่ลิตร", "คำนวณสีทาบ้าน"),
    description: "คำนวณปริมาณสีทาผนังที่ต้องใช้จากขนาดผนัง ประตูและหน้าต่าง จำนวนรอบที่ทา และอัตราการทาที่ระบุบนกระป๋อง",
    intro: [
      "กรอกความยาวและความสูงของผนัง (หรือกรอกพื้นที่โดยตรง) พื้นที่ประตูและหน้าต่าง และจำนวนรอบที่จะทา",
      "ระบบเผื่อสีไว้อีก 10% เพื่อไม่ให้สีหมดกลางคัน",
    ],
    comoSeCalcula: [
      "พื้นที่ = ความยาวผนังรวม × ความสูง แล้วหักพื้นที่ประตูและหน้าต่าง",
      "ปริมาณสี = พื้นที่ × จำนวนรอบ ÷ อัตราการทา",
      `จากนั้นบวกส่วนเผื่ออีก ${MARGEN * 100}%`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "สีหนึ่งลิตรทาได้กี่ตารางเมตร",
        respuesta: "สีทาผนังภายในส่วนใหญ่ทาได้ประมาณ 8 ถึง 12 ตร.ม. ต่อลิตรต่อรอบ (350 ถึง 400 ตร.ฟุตต่อแกลลอน) ตัวเลขที่แน่นอนระบุไว้บนกระป๋อง",
      },
      {
        pregunta: "ต้องทาสีกี่รอบ",
        respuesta: "โดยทั่วไปทา 2 รอบ ผนังปูนใหม่ ผนังที่ดูดสีมาก หรือการเปลี่ยนสีจากเข้มเป็นอ่อนอาจต้องทารอบที่สาม",
      },
      {
        pregunta: "ควรหักพื้นที่ประตูและหน้าต่างหรือไม่",
        respuesta: "ควรหักหากมีขนาดใหญ่ ส่วนช่องเล็ก ๆ ไม่ต้องหัก เพราะสีส่วนที่เหลือจะใช้กับขอบและมุมผนัง",
      },
    ],
    glosario: [
      { termino: "อัตราการทา", definicion: "พื้นที่ที่สีหนึ่งลิตรหรือหนึ่งแกลลอนทาได้ในหนึ่งรอบ" },
      { termino: "รอบ", definicion: "ชั้นของสีแต่ละชั้นที่ทาลงบนผนัง" },
    ],
  };
};
