import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoHe: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `בחדר עם 48 רגל של קירות בגובה 8 רגל, ועם 40 רגל רבוע של דלתות וחלונות, יש ${n(neta, 0)} רגל רבוע לצביעה.`,
          `עם 2 שכבות וצבע שמכסה 350 רגל רבוע לגלון צריך ${n(gal, 2)} גלונים. עם התוספת, ${n(gal * (1 + MARGEN), 2)} גלונים.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `בחדר עם 14 מטר של קירות בגובה ${n(2.6)} מטר, ועם 4 מ"ר של דלתות וחלונות, יש ${n(neta)} מ"ר לצביעה.`,
          `עם 2 שכבות וצבע שמכסה 10 מ"ר לליטר צריך ${n(litros, 2)} ליטרים. עם התוספת, ${n(litros * (1 + MARGEN), 2)} ליטרים.`,
        ];
      })();
  return {
    h1: "מחשבון צבע לקירות",
    title: tituloQueEntre("מחשבון צבע לקירות: כמה צבע צריך", "מחשבון צבע לקירות", "מחשבון צבע"),
    description: "חשבו כמה צבע צריך לקירות לפי המידות, הדלתות והחלונות, מספר השכבות וכושר הכיסוי שכתוב על הדלי.",
    intro: [
      "הזינו את האורך והגובה של הקירות (או ישירות את השטח), כמה מקום תופסים הדלתות והחלונות וכמה שכבות תצבעו.",
      "המחשבון מוסיף 10% כדי שהצבע לא ייגמר באמצע העבודה.",
    ],
    comoSeCalcula: [
      "שטח = האורך הכולל של הקירות × הגובה, פחות דלתות וחלונות.",
      "כמות צבע = שטח × מספר שכבות ÷ כושר כיסוי.",
      `בסוף מתווספת תוספת של ${MARGEN * 100}%.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: imperial ? "כמה שטח מכסה גלון צבע?" : "כמה שטח מכסה ליטר צבע?",
        respuesta: 'רוב צבעי הקירות לפנים הבית מכסים 8 עד 12 מ"ר לליטר בשכבה אחת (בערך 350 עד 400 רגל רבוע לגלון). הנתון המדויק כתוב על הדלי.',
      },
      {
        pregunta: "כמה שכבות צריך?",
        respuesta: "בדרך כלל שתי שכבות. טיח חדש, קיר סופג מאוד או מעבר חד בין צבעים עשויים לדרוש שכבה שלישית.",
      },
      {
        pregunta: "צריך להוריד את הדלתות והחלונות מהחישוב?",
        respuesta: "כן, אם הם גדולים. עדיף לא להוריד פתחים קטנים: העודף מכסה את הפינות ואת הקצוות.",
      },
    ],
    glosario: [
      { termino: "כושר כיסוי", definicion: imperial ? "כמה שטח מכסה גלון צבע בשכבה אחת." : "כמה שטח מכסה ליטר צבע בשכבה אחת." },
      { termino: "שכבה", definicion: "כל מריחה של צבע על הקיר." },
    ],
  };
};
