import { GRAMATICA } from "../../../i18n/gramatica";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const g = GRAMATICA.el;
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `Ένα δωμάτιο με 48 ft τοίχους, ύψος 8 ft και 40 ft² πόρτες και παράθυρα έχει ${n(neta, 0)} ft² για βάψιμο.`,
          `Με 2 χέρια και χρώμα που καλύπτει 350 ft² το γαλόνι, χρειάζεστε ${n(gal, 2)} γαλόνια. Με το περιθώριο, ${n(gal * (1 + MARGEN), 2)} γαλόνια.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `Ένα δωμάτιο με 14 m τοίχους, ύψος ${n(2.6)} m και 4 m² πόρτες και παράθυρα έχει ${n(neta)} m² για βάψιμο.`,
          `Με 2 χέρια και χρώμα που καλύπτει 10 m² το λίτρο, χρειάζεστε ${n(litros, 2)} λίτρα. Με το περιθώριο, ${n(litros * (1 + MARGEN), 2)} λίτρα.`,
        ];
      })();
  return {
    h1: "Υπολογισμός χρώματος για βάψιμο",
    title: tituloQueEntre(`Υπολογισμός χρώματος ${g.en(ctx.nombrePais)}`, "Υπολογισμός χρώματος για βάψιμο", "Υπολογισμός χρώματος"),
    description: "Υπολογίστε πόσο χρώμα χρειάζεστε για τους τοίχους σας από τις διαστάσεις, τις πόρτες και τα παράθυρα, τα χέρια και την απόδοση της συσκευασίας.",
    intro: [
      "Εισάγετε το μήκος και το ύψος των τοίχων (ή απευθείας την επιφάνεια), όσο πιάνουν οι πόρτες και τα παράθυρα και πόσα χέρια θα περάσετε.",
      "Ο υπολογισμός προσθέτει 10% επιπλέον, για να μη σας τελειώσει το χρώμα στη μέση της δουλειάς.",
    ],
    comoSeCalcula: [
      "Επιφάνεια = συνολικό μήκος των τοίχων × ύψος, μείον πόρτες και παράθυρα.",
      "Χρώμα = επιφάνεια × χέρια ÷ απόδοση.",
      `Στο τέλος προστίθεται περιθώριο ${MARGEN * 100}%.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Πόση επιφάνεια καλύπτει ένα λίτρο χρώμα;",
        respuesta: "Τα περισσότερα πλαστικά χρώματα εσωτερικού χώρου καλύπτουν περίπου 8 έως 12 m² το λίτρο σε κάθε χέρι. Η ακριβής τιμή αναγράφεται στη συσκευασία.",
      },
      {
        pregunta: "Πόσα χέρια χρειάζονται;",
        respuesta: "Συνήθως δύο. Ένας καινούργιος σοβάς, ένας πολύ απορροφητικός τοίχος ή μια μεγάλη αλλαγή χρώματος μπορεί να θέλουν και τρίτο.",
      },
      {
        pregunta: "Πρέπει να αφαιρέσω τις πόρτες και τα παράθυρα;",
        respuesta: "Ναι, αν είναι μεγάλα. Τα μικρά καλύτερα να μην τα αφαιρέσετε: το επιπλέον χρώμα καλύπτει τις άκρες και τα τελειώματα.",
      },
    ],
    glosario: [
      { termino: "Απόδοση", definicion: "Πόση επιφάνεια καλύπτει ένα λίτρο ή ένα γαλόνι χρώμα σε ένα χέρι." },
      { termino: "Χέρι", definicion: "Κάθε στρώση χρώματος που περνάτε στον τοίχο." },
    ],
  };
};
