import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `В комнате с общей длиной стен 48 футов, высотой 8 футов и дверями и окнами на 40 кв. футов красить нужно ${n(neta, 0)} кв. футов.`,
          `При 2 слоях и расходе 350 кв. футов на галлон понадобится ${n(gal, 2)} галлона краски. С запасом это ${n(gal * (1 + MARGEN), 2)} галлона.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `В комнате с общей длиной стен 14 м, высотой ${n(2.6)} м и дверями и окнами на 4 м² красить нужно ${n(neta)} м².`,
          `При 2 слоях и расходе 10 м² на литр понадобится ${n(litros, 2)} литра краски. С запасом это ${n(litros * (1 + MARGEN), 2)} литра.`,
        ];
      })();
  return {
    h1: "Калькулятор краски для стен",
    title: tituloQueEntre(`Калькулятор краски: ${ctx.nombrePais}`, "Калькулятор краски для стен", "Калькулятор краски"),
    description: "Рассчитайте, сколько краски нужно для стен, по их размерам, дверям и окнам, количеству слоев и расходу, указанному на банке.",
    intro: [
      "Введите длину и высоту стен (или сразу площадь), сколько занимают двери и окна и сколько слоев вы нанесете.",
      "Калькулятор добавляет 10% запаса, чтобы краска не закончилась на середине работы.",
    ],
    comoSeCalcula: [
      "Площадь = общая длина стен × высота, минус двери и окна.",
      "Краска = площадь × количество слоев ÷ расход.",
      `К результату добавляется запас ${n(MARGEN * 100, 0)}%.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Сколько краски нужно на 1 м² стены?",
        respuesta: `Большинство интерьерных красок покрывают от 8 до 12 м² на литр за один слой, то есть на 1 м² уходит около ${n(0.1)} литра на слой. Точное значение указано на банке.`,
      },
      {
        pregunta: "Сколько слоев краски наносить?",
        respuesta: "Обычно два слоя. Новая штукатурка, очень пористые стены или резкая смена цвета могут потребовать третьего.",
      },
      {
        pregunta: "Нужно ли вычитать двери и окна?",
        respuesta: "Да, если они большие. Маленькие лучше не вычитать: этот запас уйдет на углы и края.",
      },
    ],
    glosario: [
      { termino: "Расход краски", definicion: "Какую площадь покрывает литр или галлон краски за один слой." },
      { termino: "Слой", definicion: "Каждый проход краской по стене." },
    ],
  };
};
