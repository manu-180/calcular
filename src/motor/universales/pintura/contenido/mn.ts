import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoMn: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `Нийт 48 фут урт, 8 фут өндөр ханатай, хаалга цонх нь 40 кв. фут эзэлдэг өрөөнд будах талбай ${n(neta, 0)} кв. фут байна.`,
          `2 давхар будахад, нэг галлон нь 350 кв. фут бүрхдэг будгаар ${n(gal, 2)} галлон шаардлагатай. Нөөцтэй нь ${n(gal * (1 + MARGEN), 2)} галлон болно.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `Нийт 14 м урт, ${n(2.6)} м өндөр ханатай, хаалга цонх нь 4 м² эзэлдэг өрөөнд будах талбай ${n(neta)} м² байна.`,
          `2 давхар будахад, нэг литр нь 10 м² бүрхдэг будгаар ${n(litros, 2)} литр шаардлагатай. Нөөцтэй нь ${n(litros * (1 + MARGEN), 2)} литр болно.`,
        ];
      })();
  return {
    h1: "Будгийн тооцоолуур",
    title: tituloQueEntre(`Будгийн тооцоолуур: ${ctx.nombrePais}`, "Хэр их будаг хэрэгтэй вэ: тооцоолох", "Будгийн тооцоолуур"),
    description: "Ханын хэмжээ, хаалга цонх, будах давхрын тоо, савны шошгон дээрх зарцуулалтаар хэр их будаг хэрэгтэйг тооцоолно уу.",
    intro: [
      "Ханын урт, өндөр (эсвэл шууд талбай), хаалга цонх хэр зай эзэлдэг, хэдэн давхар будахаа оруулна уу.",
      "Ажлын дундуур будаг дуусахгүйн тулд тооцоолуур 10 хувийн нөөц нэмдэг.",
    ],
    comoSeCalcula: [
      "Талбай = ханын нийт урт × өндөр, хаалга цонхыг хассан.",
      "Будаг = талбай × давхрын тоо ÷ зарцуулалт.",
      `Эцэст нь ${MARGEN * 100}% нөөц нэмнэ.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Нэг литр будаг хэр их талбай бүрхэх вэ?",
        respuesta: "Дотор ханын ихэнх будаг нэг давхраар литр тутамд 8 ба 12 м² хооронд (галлон тутамд 350 ба 400 кв. фут орчим) бүрхдэг. Яг утга нь савны шошгон дээр бичээстэй байдаг.",
      },
      {
        pregunta: "Хэдэн давхар будах шаардлагатай вэ?",
        respuesta: "Ихэвчлэн хоёр давхар хангалттай. Шинэ шавардлага, будаг их шингээдэг хана эсвэл өнгийг эрс өөрчлөхөд гурав дахь давхар шаардлагатай байж болно.",
      },
      {
        pregunta: "Хаалга, цонхыг хасах хэрэгтэй юу?",
        respuesta: "Том бол тийм. Жижгийг хасахгүй байх нь дээр: илүү гарсан будаг нь ирмэг, булангуудад хэрэг болно.",
      },
    ],
    glosario: [
      { termino: "Будгийн зарцуулалт", definicion: "Нэг литр эсвэл галлон будаг нэг давхраар хэр их талбай бүрхэх хэмжээ." },
      { termino: "Давхар", definicion: "Хананд будаг нэг удаа түрхэх үйлдэл." },
    ],
  };
};
