import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoBn: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const e = (x: number) => formatearNumero(ctx, x, 0);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `একটি ঘরের দেয়ালের মোট দৈর্ঘ্য ${e(48)} ফুট, উচ্চতা ${e(8)} ফুট আর দরজা-জানালা ${e(40)} বর্গফুট হলে রং করতে হবে ${n(neta, 0)} বর্গফুট।`,
          `${e(2)} কোট রং আর প্রতি গ্যালনে ${e(350)} বর্গফুট কভারেজ হলে লাগবে ${n(gal, 2)} গ্যালন। বাড়তি অংশসহ ${n(gal * (1 + MARGEN), 2)} গ্যালন।`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `একটি ঘরের দেয়ালের মোট দৈর্ঘ্য ${e(14)} মিটার, উচ্চতা ${n(2.6)} মিটার আর দরজা-জানালা ${e(4)} বর্গমিটার হলে রং করতে হবে ${n(neta)} বর্গমিটার।`,
          `${e(2)} কোট রং আর প্রতি লিটারে ${e(10)} বর্গমিটার কভারেজ হলে লাগবে ${n(litros, 2)} লিটার। বাড়তি অংশসহ ${n(litros * (1 + MARGEN), 2)} লিটার।`,
        ];
      })();
  return {
    h1: "রং হিসাবের ক্যালকুলেটর",
    title: tituloQueEntre(`পেইন্ট ক্যালকুলেটর | ${ctx.nombrePais}`, "পেইন্ট ক্যালকুলেটর"),
    description: "দেয়ালের মাপ, দরজা-জানালা, কয় কোট আর কৌটার কভারেজ দিয়ে জানুন আপনার দেয়াল রং করতে কত লিটার রং লাগবে।",
    intro: [
      "দেয়ালের দৈর্ঘ্য আর উচ্চতা (অথবা সরাসরি ক্ষেত্রফল), দরজা-জানালা কতটা জায়গা নেয় আর কয় কোট রং দেবেন, তা দিন।",
      `মাঝপথে রং যেন ফুরিয়ে না যায়, তাই ${e(MARGEN * 100)}% বেশি ধরা হয়।`,
    ],
    comoSeCalcula: [
      "ক্ষেত্রফল = দেয়ালগুলোর মোট দৈর্ঘ্য × উচ্চতা, তারপর দরজা-জানালা বাদ।",
      "রং = ক্ষেত্রফল × কোট ÷ কভারেজ।",
      `শেষে ${e(MARGEN * 100)}% বাড়তি যোগ করা হয়।`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "এক লিটার রঙে কতটা জায়গা হয়?",
        respuesta: `ঘরের ভেতরের দেয়ালের বেশিরভাগ রং প্রতি কোটে প্রতি লিটারে প্রায় ${e(8)} থেকে ${e(12)} বর্গমিটার (প্রতি গ্যালনে ${e(350)} থেকে ${e(400)} বর্গফুট) ঢাকে। সঠিক সংখ্যাটি কৌটায় লেখা থাকে।`,
      },
      {
        pregunta: "কয় কোট রং লাগে?",
        respuesta: "সাধারণত দুই কোট। নতুন প্লাস্টার, খুব শোষক দেয়াল বা রঙে বড় পরিবর্তন হলে তৃতীয় কোট লাগতে পারে। নতুন দেয়ালে আগে প্রাইমার দিলে রং কম লাগে।",
      },
      {
        pregunta: "দরজা-জানালা কি বাদ দেব?",
        respuesta: "বড় হলে বাদ দিন। ছোটগুলো বাদ না দেওয়াই ভালো, বাড়তি রংটুকু কোনা আর কিনারায় কাজে লাগে।",
      },
    ],
    glosario: [
      { termino: "কভারেজ", definicion: "এক লিটার বা এক গ্যালন রং এক কোটে কতটা জায়গা ঢাকে।" },
      { termino: "কোট", definicion: "দেয়ালে দেওয়া রঙের প্রতিটি স্তর।" },
    ],
  };
};
