import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `Стая с 48 фута стени, високи 8 фута, и 40 кв. фута врати и прозорци има ${n(neta, 0)} кв. фута за боядисване.`,
          `При 2 слоя и боя, която покрива 350 кв. фута с галон, са нужни ${n(gal, 2)} галона. С резерва това са ${n(gal * (1 + MARGEN), 2)} галона.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `Стая с 14 м стени, високи ${n(2.6)} м, и 4 м² врати и прозорци има ${n(neta)} м² за боядисване.`,
          `При 2 слоя и боя, която покрива 10 м² с литър, са нужни ${n(litros, 2)} литра. С резерва това са ${n(litros * (1 + MARGEN), 2)} литра.`,
        ];
      })();
  return {
    h1: "Калкулатор за боя",
    title: tituloQueEntre(`Калкулатор за боя: ${ctx.nombrePais}`, "Колко боя ми трябва: калкулатор", "Калкулатор за боя"),
    description: "Изчислете колко боя е нужна за стените според размерите им, вратите и прозорците, броя на слоевете и разходната норма от кутията.",
    intro: [
      "Въведете дължината и височината на стените (или директно площта), колко място заемат вратите и прозорците и колко слоя ще нанесете.",
      "Калкулаторът добавя 10% резерв, за да не Ви свърши боята по средата на работата.",
    ],
    comoSeCalcula: [
      "Площ = обща дължина на стените × височина, минус вратите и прозорците.",
      "Боя = площ × брой слоеве ÷ разходна норма.",
      `Накрая се добавя резерв от ${MARGEN * 100}%.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Колко площ покрива един литър боя?",
        respuesta: "Повечето интериорни бои покриват от 8 до 12 м² с литър на един слой (около 350 до 400 кв. фута с галон). Точната стойност е написана на кутията.",
      },
      {
        pregunta: "Колко слоя са нужни?",
        respuesta: "Обичайно са два слоя. Нова мазилка, силно попиващи стени или голяма смяна на цвета може да изискват и трети.",
      },
      {
        pregunta: "Трябва ли да изваждам вратите и прозорците?",
        respuesta: "Да, ако са големи. Малките е по-добре да не ги изваждате: излишъкът покрива ръбовете и ъглите.",
      },
    ],
    glosario: [
      { termino: "Разходна норма", definicion: "Колко площ покрива един литър или галон боя с един слой." },
      { termino: "Слой", definicion: "Всяко нанасяне на боя върху стената." },
    ],
  };
};
