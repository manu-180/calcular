import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `Просторија со 48 стапки ѕидови, високи 8 стапки, и 40 кв. стапки врати и прозорци има ${n(neta, 0)} кв. стапки за боење.`,
          `Со 2 слоја и боја што покрива 350 кв. стапки со галон, потребни се ${n(gal, 2)} галони. Со резервата тоа се ${n(gal * (1 + MARGEN), 2)} галони.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `Просторија со 14 м ѕидови, високи ${n(2.6)} м, и 4 м² врати и прозорци има ${n(neta)} м² за боење.`,
          `Со 2 слоја и боја што покрива 10 м² со литар, потребни се ${n(litros, 2)} литри. Со резервата тоа се ${n(litros * (1 + MARGEN), 2)} литри.`,
        ];
      })();
  return {
    h1: "Калкулатор за боја",
    title: tituloQueEntre(`Калкулатор за боја: ${ctx.nombrePais}`, "Колку боја ми треба: калкулатор", "Калкулатор за боја"),
    description: "Пресметајте колку боја ви треба за ѕидовите според мерките, вратите и прозорците, бројот на слоеви и покривноста од кантата.",
    intro: [
      "Внесете ги должината и висината на ѕидовите (или директно површината), колку простор зафаќаат вратите и прозорците и колку слоеви ќе нанесете.",
      "Калкулаторот додава 10 % резерва, за да не ви снема боја на средина од работата.",
    ],
    comoSeCalcula: [
      "Површина = вкупна должина на ѕидовите × висина, минус вратите и прозорците.",
      "Боја = површина × број на слоеви ÷ покривност.",
      `На крајот се додава резерва од ${MARGEN * 100} %.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Колку површина покрива еден литар боја?",
        respuesta: "Повеќето бои за внатрешни ѕидови покриваат од 8 до 12 м² со литар во еден слој (околу 350 до 400 кв. стапки со галон). Точната вредност пишува на кантата.",
      },
      {
        pregunta: "Колку слоеви се потребни?",
        respuesta: "Вообичаено се два слоја. Нов малтер, ѕидови што силно впиваат или голема промена на бојата може да бараат и трет.",
      },
      {
        pregunta: "Дали треба да ги одземам вратите и прозорците?",
        respuesta: "Да, ако се големи. Малите подобро е да не ги одземате: вишокот ги покрива рабовите и аглите.",
      },
    ],
    glosario: [
      { termino: "Покривност", definicion: "Колку површина покрива еден литар или галон боја со еден слој." },
      { termino: "Слој", definicion: "Секое нанесување боја на ѕидот." },
    ],
  };
};
