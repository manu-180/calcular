import { contenidoArabe } from "../../comun/arabe";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoAr: ContenidoUniversal = contenidoArabe((ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `غرفة طول جدرانها 48 قدمًا وارتفاعها 8 أقدام، وفيها أبواب ونوافذ مساحتها 40 قدمًا مربعًا، تكون مساحة الطلاء فيها ${n(neta, 0)} قدم².`,
          `مع طبقتين وطلاء يغطي 350 قدمًا مربعًا للغالون، تحتاج إلى ${n(gal, 2)} غالون. ومع هامش الاحتياط ${n(gal * (1 + MARGEN), 2)} غالون.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `غرفة طول جدرانها 14 مترًا وارتفاعها ${n(2.6)} م، وفيها أبواب ونوافذ مساحتها 4 م²، تكون مساحة الطلاء فيها ${n(neta)} م².`,
          `مع طبقتين وطلاء يغطي 10 م² للتر، تحتاج إلى ${n(litros, 2)} لتر. ومع هامش الاحتياط ${n(litros * (1 + MARGEN), 2)} لتر.`,
        ];
      })();
  return {
    h1: "حاسبة كمية الطلاء",
    title: tituloQueEntre(`حاسبة كمية الطلاء في ${ctx.nombrePais}`, "حاسبة كمية الطلاء للجدران", "حاسبة الطلاء"),
    description: "احسب كمية الطلاء التي تحتاجها لجدرانك من مساحتها والأبواب والنوافذ وعدد الطبقات والتغطية المكتوبة على العبوة.",
    intro: [
      "أدخل طول الجدران وارتفاعها (أو المساحة مباشرة)، والمساحة التي تشغلها الأبواب والنوافذ، وعدد الطبقات التي ستطليها.",
      "تضيف الحاسبة 10% احتياطًا حتى لا ينفد الطلاء في منتصف العمل.",
    ],
    comoSeCalcula: [
      "المساحة = الطول الإجمالي للجدران × الارتفاع، ناقص مساحة الأبواب والنوافذ.",
      "كمية الطلاء = المساحة × عدد الطبقات ÷ التغطية.",
      `ثم يُضاف هامش احتياط قدره ${MARGEN * 100}%.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "كم مترًا مربعًا يغطي لتر الطلاء؟",
        respuesta: "معظم طلاءات الجدران الداخلية تغطي من 8 إلى 12 م² للتر في الطبقة الواحدة (نحو 350 إلى 400 قدم مربع للغالون). والرقم الدقيق مكتوب على العبوة.",
      },
      {
        pregunta: "كم طبقة أحتاج؟",
        respuesta: "طبقتان هو المعتاد. وقد تحتاج إلى طبقة ثالثة مع اللياسة الجديدة أو الجدران كثيرة المسام أو عند تغيير اللون تغييرًا كبيرًا.",
      },
      {
        pregunta: "هل أطرح مساحة الأبواب والنوافذ؟",
        respuesta: "نعم إذا كانت كبيرة. والأفضل ألا تطرح الصغيرة، لأن الكمية الزائدة تغطي الحواف والزوايا.",
      },
    ],
    glosario: [
      { termino: "التغطية", definicion: "المساحة التي يغطيها لتر أو غالون من الطلاء في طبقة واحدة." },
      { termino: "الطبقة", definicion: "كل وجه من الطلاء يُدهن على الجدار." },
    ],
  };
});
