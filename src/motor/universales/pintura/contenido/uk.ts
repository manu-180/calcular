import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";
import { MARGEN } from "../definicion";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 1) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const pct = formatearNumero(ctx, MARGEN * 100, 0);
  const ejemplo = imperial
    ? (() => {
        const neta = 48 * 8 - 40;
        const gal = (neta * 2) / 350;
        return [
          `У кімнаті із загальною довжиною стін 48 ft, висотою 8 ft і дверима та вікнами на 40 ft² площа для фарбування становить ${n(neta, 0)} ft².`,
          `Фарбою, галон якої покриває 350 ft², на 2 шари потрібно ${n(gal, 2)} галона. Із запасом варто купити ${n(gal * (1 + MARGEN), 2)} галона.`,
        ];
      })()
    : (() => {
        const neta = 14 * 2.6 - 4;
        const litros = (neta * 2) / 10;
        return [
          `У кімнаті із загальною довжиною стін 14 м, висотою ${n(2.6)} м і дверима та вікнами на 4 м² площа для фарбування становить ${n(neta)} м².`,
          `Фарбою, літр якої покриває 10 м², на 2 шари потрібно ${n(litros, 2)} літра. Із запасом варто купити ${n(litros * (1 + MARGEN), 2)} літра.`,
        ];
      })();
  return {
    h1: "Калькулятор фарби: скільки фарби потрібно",
    title: tituloQueEntre(
      `Скільки фарби потрібно: калькулятор, ${ctx.nombrePais}`,
      "Калькулятор фарби: скільки фарби потрібно",
      "Скільки фарби потрібно",
    ),
    description: "Розрахуйте, скільки фарби потрібно, за розмірами стін, дверима й вікнами, кількістю шарів і витратою, вказаною на банці.",
    intro: [
      "Введіть довжину і висоту стін (або одразу площу), площу дверей і вікон та кількість шарів фарби.",
      `Щоб фарба не закінчилася посеред роботи, додається запас ${pct}%.`,
    ],
    comoSeCalcula: [
      "Площа = загальна довжина стін × висота, мінус двері й вікна.",
      "Фарба = площа × кількість шарів ÷ витрата.",
      `До результату додається запас ${pct}%.`,
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Скільки квадратних метрів фарбує літр фарби?",
        respuesta: "Більшість інтерʼєрних фарб для стін покривають за один шар приблизно від 8 до 12 м² на літр (від 350 до 400 ft² на галон). Точне значення вказано на банці.",
      },
      {
        pregunta: "Скільки шарів фарби потрібно?",
        respuesta: "Зазвичай два. Свіжа штукатурка, дуже вбирні стіни чи різка зміна кольору можуть потребувати третього шару.",
      },
      {
        pregunta: "Чи віднімати двері й вікна?",
        respuesta: "Великі варто відняти. Малі краще не віднімати: надлишок піде на краї і кути.",
      },
    ],
    glosario: [
      { termino: "Витрата фарби", definicion: "Площа, яку літр чи галон фарби покриває за один шар." },
      { termino: "Шар", definicion: "Кожне нанесення фарби на стіну." },
    ],
  };
};
