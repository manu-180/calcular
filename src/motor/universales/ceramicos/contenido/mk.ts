import { GRAMATICA } from "../../../i18n/gramatica";
import { pluralMk } from "../../../i18n/plural";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoMk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const kutii = (k: number) => pluralMk(k, "кутија", "кутии");
  const ejemplo = imperial
    ? (() => {
        const piezas = Math.ceil((150 * 1.1) / 1 - 1e-9);
        return [
          `За 150 ft² со плочки 12 × 12 in (по 1 ft² секоја) и 10 % резерва се потребни ${piezas} плочки.`,
          `Ако во кутија има 10 плочки, тоа се ${kutii(Math.ceil(piezas / 10))}.`,
        ];
      })()
    : (() => {
        const pieza = 0.6 * 0.6;
        const piezas = Math.ceil((20 * 1.1) / pieza - 1e-9);
        return [
          `За 20 m² со плочки 60 × 60 cm (по ${n(pieza)} m² секоја) и 10 % резерва се потребни ${piezas} плочки.`,
          `Ако во кутија има 4 плочки, тоа се ${kutii(Math.ceil(piezas / 4))}.`,
        ];
      })();
  return {
    h1: "Калкулатор за плочки",
    title: tituloQueEntre(`Калкулатор за плочки ${GRAMATICA.mk.en(ctx.nombrePais)}`, "Подни и ѕидни плочки", "Калкулатор за плочки"),
    description: "Пресметајте колку подни или ѕидни плочки ви се потребни, со резерва за отпад, и колку кутии да купите.",
    intro: [
      "Внесете ја површината, големината на една плочка и колку плочки има во кутија. Ќе видите колку плочки и кутии да купите.",
      "Резервата за отпад го покрива сечењето по рабовите и случајно скршените плочки.",
    ],
    comoSeCalcula: [
      `Површина на една плочка = должина × ширина, претворена во ${imperial ? "квадратни стапки" : "квадратни метри"}.`,
      "Плочки = површина × (1 + резерва ÷ 100) ÷ површина на една плочка, заокружено нагоре.",
      "Кутии = плочки ÷ плочки во кутија, заокружено нагоре.",
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Колкава резерва за отпад да предвидам?",
        respuesta: "10 % при право редење. При дијагонално редење, шема рибина коска или простории со многу сечење, 15 % до 20 %.",
      },
      {
        pregunta: "Дали треба да ги сметам фугите?",
        respuesta: "Не. Фугите се широки неколку милиметри и резервата за отпад веќе ја покрива разликата.",
      },
      {
        pregunta: "Дали да купам неколку плочки повеќе?",
        respuesta: "Да, неколку резервни плочки од истата партија. Ако подоцна некоја се скрши, тешко ќе ја најдете истата нијанса.",
      },
    ],
    glosario: [
      { termino: "Отпад", definicion: "Материјалот што се губи при сечење и кршење. Се купува како процент повеќе." },
      { termino: "Партија", definicion: "Една производна серија. Плочките од различни партии може малку да се разликуваат по боја." },
    ],
  };
};
