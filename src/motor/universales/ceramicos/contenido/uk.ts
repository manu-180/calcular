import { pluralUk } from "../../../i18n/plural";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoUk: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const plitky = (k: number) => pluralUk(k, "плитка", "плитки", "плиток");
  const korobky = (k: number) => pluralUk(k, "коробка", "коробки", "коробок");
  const ejemplo = imperial
    ? (() => {
        const piezas = Math.ceil((150 * 1.1) / 1 - 1e-9);
        return [
          `На площу 150 ft² плиткою 12 × 12 in (кожна по 1 ft²) із запасом 10% потрібно ${plitky(piezas)}.`,
          `Якщо в коробці 10 плиток, купити варто ${korobky(Math.ceil(piezas / 10))}.`,
        ];
      })()
    : (() => {
        const pieza = 0.6 * 0.6;
        const piezas = Math.ceil((20 * 1.1) / pieza - 1e-9);
        return [
          `На площу 20 м² плиткою 60 × 60 см (кожна по ${n(pieza)} м²) із запасом 10% потрібно ${plitky(piezas)}.`,
          `Якщо в коробці 4 плитки, купити варто ${korobky(Math.ceil(piezas / 4))}.`,
        ];
      })();
  return {
    h1: "Калькулятор плитки: скільки плитки потрібно",
    title: tituloQueEntre(
      `Скільки плитки потрібно: калькулятор, ${ctx.nombrePais}`,
      "Калькулятор плитки: скільки коробок купити",
      "Скільки плитки потрібно",
    ),
    description: "Розрахуйте, скільки плитки потрібно на підлогу чи стіну, із запасом на підрізку, і скільки коробок купити.",
    intro: [
      "Введіть площу, розмір однієї плитки і кількість плиток у коробці. Ви побачите, скільки плиток і коробок потрібно купити.",
      "Запас на підрізку покриває обрізання по краях і плитки, що розколюються під час роботи.",
    ],
    comoSeCalcula: [
      `Площа однієї плитки = довжина × ширина, у ${imperial ? "квадратних футах" : "квадратних метрах"}.`,
      "Кількість плиток = площа × (1 + запас ÷ 100) ÷ площа однієї плитки, з округленням угору.",
      "Коробки = кількість плиток ÷ плиток у коробці, з округленням угору.",
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Який запас на підрізку закладати?",
        respuesta: "Для прямого укладання 10%. Для діагонального укладання, ялинки або кімнат, де багато підрізки, від 15% до 20%.",
      },
      {
        pregunta: "Чи враховувати шви між плитками?",
        respuesta: "Ні. Шви мають ширину кілька міліметрів, і запас на підрізку вже покриває цю різницю.",
      },
      {
        pregunta: "Чи варто купити трохи більше?",
        respuesta: "Так, візьміть кілька запасних плиток з тієї самої партії. Якщо згодом одна розколеться, знайти такий самий відтінок може бути складно.",
      },
    ],
    glosario: [
      { termino: "Запас на підрізку", definicion: "Відсоток плитки, який докуповують на обрізання і бій." },
      { termino: "Партія", definicion: "Виробнича серія. Відтінок плитки з різних партій може трохи відрізнятися." },
    ],
  };
};
