import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoBn: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const e = (x: number) => formatearNumero(ctx, x, 0);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const piezas = Math.ceil((150 * 1.1) / 1 - 1e-9);
        return [
          `${e(150)} বর্গফুটে ${e(12)} × ${e(12)} ইঞ্চির টাইলস (প্রতিটি ${e(1)} বর্গফুট) আর ${e(10)}% অপচয় ধরলে লাগবে ${e(piezas)}টি টাইলস।`,
          `এক বাক্সে ${e(10)}টি থাকলে কিনতে হবে ${e(Math.ceil(piezas / 10))} বাক্স।`,
        ];
      })()
    : (() => {
        const pieza = 0.6 * 0.6;
        const piezas = Math.ceil((20 * 1.1) / pieza - 1e-9);
        return [
          `${e(20)} বর্গমিটারে ${e(60)} × ${e(60)} সেন্টিমিটারের টাইলস (প্রতিটি ${n(pieza)} বর্গমিটার) আর ${e(10)}% অপচয় ধরলে লাগবে ${e(piezas)}টি টাইলস।`,
          `এক বাক্সে ${e(4)}টি থাকলে কিনতে হবে ${e(Math.ceil(piezas / 4))} বাক্স।`,
        ];
      })();
  return {
    h1: "টাইলস হিসাবের ক্যালকুলেটর",
    title: tituloQueEntre(`টাইলস হিসাব | ${ctx.nombrePais}`, "টাইলস ক্যালকুলেটর"),
    description: "মেঝে বা দেয়ালের জন্য অপচয়সহ কয়টি টাইলস লাগবে আর কয় বাক্স কিনতে হবে, তা বের করুন।",
    intro: [
      "ক্ষেত্রফল, প্রতিটি টাইলসের মাপ আর এক বাক্সে কয়টি থাকে, তা দিন। কয়টি টাইলস আর কয় বাক্স কিনতে হবে, দেখতে পাবেন।",
      "অপচয়ের বাড়তি অংশ ধরা হয় কিনারার কাটা আর মাঝেমধ্যে ভেঙে যাওয়া টাইলসের জন্য।",
    ],
    comoSeCalcula: [
      `একটি টাইলসের ক্ষেত্রফল = দৈর্ঘ্য × প্রস্থ, ${imperial ? "বর্গফুটে" : "বর্গমিটারে"} বদলে।`,
      `টাইলস = ক্ষেত্রফল × (${e(1)} + অপচয় ÷ ${e(100)}) ÷ একটি টাইলসের ক্ষেত্রফল, উপরের পূর্ণসংখ্যায়।`,
      "বাক্স = টাইলস ÷ প্রতি বাক্সের টাইলস, উপরের পূর্ণসংখ্যায়।",
    ],
    ejemplo,
    faq: [
      {
        pregunta: "অপচয়ের জন্য কতটা বাড়তি ধরব?",
        respuesta: `সোজা বসালে ${e(10)}%। কোনাকুনি বা হেরিংবোন নকশায়, কিংবা অনেক কাটা লাগে এমন ঘরে ${e(15)}% থেকে ${e(20)}%।`,
      },
      {
        pregunta: "জোড়ের ফাঁক কি আলাদা করে হিসাব করতে হবে?",
        respuesta: "না। জোড়ের ফাঁক মাত্র কয়েক মিলিমিটার, আর অপচয়ের বাড়তি অংশেই সেই পার্থক্য ঢাকা পড়ে যায়।",
      },
      {
        pregunta: "কিছু বেশি কিনে রাখা কি ভালো?",
        respuesta: "হ্যাঁ, একই লটের কয়েকটি বাড়তি টাইলস রেখে দিন। পরে একটি ভাঙলে একই রঙের টাইলস খুঁজে পাওয়া কঠিন হতে পারে।",
      },
    ],
    glosario: [
      { termino: "অপচয়", definicion: "কাটা আর ভাঙার জন্য যে বাড়তি শতাংশ কেনা হয়।" },
      { termino: "লট", definicion: "একবারে তৈরি হওয়া টাইলসের চালান। আলাদা লটের টাইলসের রং সামান্য আলাদা হতে পারে।" },
    ],
  };
};
