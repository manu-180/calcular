import { pluralRu } from "../../../i18n/plural";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

const plitki = (k: number) => pluralRu(k, "плитка", "плитки", "плиток");
const korobki = (k: number) => pluralRu(k, "коробка", "коробки", "коробок");

export const contenidoRu: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const ejemplo = imperial
    ? (() => {
        const piezas = Math.ceil((150 * 1.1) / 1 - 1e-9);
        return [
          `Для 150 кв. футов плиткой 12 × 12 дюймов (1 кв. фут каждая) с запасом 10% понадобится ${plitki(piezas)}.`,
          `Если в коробке 10 плиток, нужно купить ${korobki(Math.ceil(piezas / 10))}.`,
        ];
      })()
    : (() => {
        const pieza = 0.6 * 0.6;
        const piezas = Math.ceil((20 * 1.1) / pieza - 1e-9);
        return [
          `Для 20 м² плиткой 60 × 60 см (${n(pieza)} м² каждая) с запасом 10% понадобится ${plitki(piezas)}.`,
          `Если в коробке 4 плитки, нужно купить ${korobki(Math.ceil(piezas / 4))}.`,
        ];
      })();
  return {
    h1: "Калькулятор плитки",
    title: tituloQueEntre(`Калькулятор плитки: ${ctx.nombrePais}`, "Калькулятор плитки для пола и стен", "Калькулятор плитки"),
    description: "Рассчитайте, сколько плитки нужно на пол или стену с учетом запаса на подрезку и сколько коробок купить.",
    intro: [
      "Введите площадь, размер одной плитки и сколько штук в коробке. Калькулятор покажет, сколько плиток и коробок купить.",
      "Запас покрывает подрезку по краям и случайно разбитую плитку.",
    ],
    comoSeCalcula: [
      `Площадь одной плитки = длина × ширина, переведенная в ${imperial ? "квадратные футы" : "квадратные метры"}.`,
      "Плитки = площадь × (1 + запас ÷ 100) ÷ площадь одной плитки, с округлением вверх.",
      "Коробки = плитки ÷ плиток в коробке, с округлением вверх.",
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Какой запас плитки брать?",
        respuesta: "10% для прямой укладки. Для диагональной укладки, елочки или комнат со множеством подрезок берут от 15 до 20%.",
      },
      {
        pregunta: "Нужно ли учитывать швы?",
        respuesta: "Нет. Швы шириной несколько миллиметров, и запас уже покрывает эту разницу.",
      },
      {
        pregunta: "Стоит ли покупать плитку про запас?",
        respuesta: "Да, несколько лишних плиток из той же партии. Если позже какая-то разобьется, подобрать такой же оттенок бывает трудно.",
      },
      {
        pregunta: "Как посчитать количество плитки на пол?",
        respuesta: "Разделите площадь пола с запасом на площадь одной плитки и округлите вверх. Калькулятор делает это сразу и считает коробки.",
      },
    ],
    glosario: [
      { termino: "Запас на подрезку", definicion: "Дополнительный процент плитки на подрезку и бой." },
      { termino: "Партия", definicion: "Плитка одного выпуска. В разных партиях оттенок может немного отличаться." },
    ],
  };
};
