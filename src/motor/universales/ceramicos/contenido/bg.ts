import { GRAMATICA } from "../../../i18n/gramatica";
import { pluralBg } from "../../../i18n/plural";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoBg: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const kashoni = (k: number) => pluralBg(k, "кашон", "кашона");
  const ejemplo = imperial
    ? (() => {
        const piezas = Math.ceil((150 * 1.1) / 1 - 1e-9);
        return [
          `За 150 ft² с плочки 12 × 12 in (по 1 ft² всяка) и 10% резерв са нужни ${piezas} плочки.`,
          `Ако в кашон има 10 плочки, това са ${kashoni(Math.ceil(piezas / 10))}.`,
        ];
      })()
    : (() => {
        const pieza = 0.6 * 0.6;
        const piezas = Math.ceil((20 * 1.1) / pieza - 1e-9);
        return [
          `За 20 m² с плочки 60 × 60 cm (по ${n(pieza)} m² всяка) и 10% резерв са нужни ${piezas} плочки.`,
          `Ако в кашон има 4 плочки, това са ${kashoni(Math.ceil(piezas / 4))}.`,
        ];
      })();
  return {
    h1: "Калкулатор за плочки",
    title: tituloQueEntre(`Калкулатор за плочки ${GRAMATICA.bg.en(ctx.nombrePais)}`, "Калкулатор за плочки и фаянс", "Калкулатор за плочки"),
    description: "Изчислете колко плочки или фаянс са нужни за под или стена, с резерв за фира, и колко кашона да купите.",
    intro: [
      "Въведете площта, размера на една плочка и колко плочки има в кашон. Ще видите колко плочки и кашони да купите.",
      "Резервът за фира покрива рязането по краищата и случайно счупените плочки.",
    ],
    comoSeCalcula: [
      `Площ на една плочка = дължина × ширина, превърната в ${imperial ? "квадратни футове" : "квадратни метри"}.`,
      "Плочки = площ × (1 + резерв ÷ 100) ÷ площ на една плочка, закръглено нагоре.",
      "Кашони = плочки ÷ плочки в кашон, закръглено нагоре.",
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Какъв резерв за фира да предвидя?",
        respuesta: "10% при право редене. При диагонално редене, рибена кост или помещения с много рязане 15% до 20%.",
      },
      {
        pregunta: "Трябва ли да смятам фугите?",
        respuesta: "Не. Фугите са широки няколко милиметра и резервът за фира вече покрива разликата.",
      },
      {
        pregunta: "Да купя ли няколко плочки в повече?",
        respuesta: "Да, няколко резервни плочки от същата партида. Ако по-късно някоя се счупи, трудно ще намерите същия нюанс.",
      },
    ],
    glosario: [
      { termino: "Фира", definicion: "Материалът, който се губи при рязане и счупване. Купува се като процент в повече." },
      { termino: "Партида", definicion: "Една производствена серия. Плочките от различни партиди може леко да се различават по цвят." },
    ],
  };
};
