import { pluralEl } from "../../../i18n/plural";
import { formatearNumero, tituloQueEntre, type ContenidoUniversal } from "../../tipos";

export const contenidoEl: ContenidoUniversal = (ctx) => {
  const n = (x: number, d = 2) => formatearNumero(ctx, x, d);
  const imperial = ctx.unidades === "imperial";
  const plakidia = (k: number) => pluralEl(formatearNumero(ctx, k, 0), "πλακίδιο", "πλακίδια");
  const koutia = (k: number) => pluralEl(formatearNumero(ctx, k, 0), "κουτί", "κουτιά");
  const ejemplo = imperial
    ? (() => {
        const piezas = Math.ceil((150 * 1.1) / 1 - 1e-9);
        return [
          `Για επιφάνεια 150 ft² με πλακίδια 12 × 12 in (το καθένα 1 ft²) και φύρα 10% χρειάζεστε ${plakidia(piezas)}.`,
          `Αν το κουτί έχει 10 πλακίδια, αγοράστε ${koutia(Math.ceil(piezas / 10))}.`,
        ];
      })()
    : (() => {
        const pieza = 0.6 * 0.6;
        const piezas = Math.ceil((20 * 1.1) / pieza - 1e-9);
        return [
          `Για επιφάνεια 20 m² με πλακίδια 60 × 60 cm (το καθένα ${n(pieza)} m²) και φύρα 10% χρειάζεστε ${plakidia(piezas)}.`,
          `Αν το κουτί έχει 4 πλακίδια, αγοράστε ${koutia(Math.ceil(piezas / 4))}.`,
        ];
      })();
  return {
    h1: "Υπολογισμός πλακιδίων για δάπεδο και τοίχο",
    title: tituloQueEntre(
      `Υπολογισμός πλακιδίων (${ctx.nombrePais})`,
      "Υπολογισμός πλακιδίων: πόσα κουτιά να αγοράσετε",
      "Υπολογισμός πλακιδίων",
    ),
    description: "Υπολογίστε πόσα πλακίδια χρειάζεστε για δάπεδο ή τοίχο, μαζί με τη φύρα από τα κοψίματα, και πόσα κουτιά να αγοράσετε.",
    intro: [
      "Εισάγετε την επιφάνεια, τις διαστάσεις ενός πλακιδίου και πόσα έχει το κουτί. Θα δείτε πόσα πλακίδια και πόσα κουτιά χρειάζεται να αγοράσετε.",
      "Η φύρα καλύπτει τα κοψίματα στις άκρες και τα κομμάτια που σπάνε κατά την τοποθέτηση.",
    ],
    comoSeCalcula: [
      `Επιφάνεια ενός πλακιδίου = μήκος × πλάτος, σε ${imperial ? "τετραγωνικά πόδια" : "τετραγωνικά μέτρα"}.`,
      "Πλακίδια = επιφάνεια × (1 + φύρα ÷ 100) ÷ επιφάνεια ενός πλακιδίου, με στρογγυλοποίηση προς τα πάνω.",
      "Κουτιά = πλακίδια ÷ πλακίδια ανά κουτί, με στρογγυλοποίηση προς τα πάνω.",
    ],
    ejemplo,
    faq: [
      {
        pregunta: "Πόση φύρα να υπολογίσω;",
        respuesta: "Σε ίσια τοποθέτηση 10%. Σε διαγώνια, ψαροκόκαλο ή χώρους με πολλά κοψίματα 15% έως 20%.",
      },
      {
        pregunta: "Πρέπει να υπολογίσω τους αρμούς;",
        respuesta: "Όχι. Οι αρμοί είναι λίγα χιλιοστά και τη διαφορά την καλύπτει η φύρα.",
      },
      {
        pregunta: "Αξίζει να αγοράσω λίγα παραπάνω;",
        respuesta: "Ναι, κρατήστε μερικά πλακίδια από την ίδια παρτίδα. Αν αργότερα σπάσει κάποιο, η ίδια απόχρωση μπορεί να μη βρίσκεται εύκολα.",
      },
    ],
    glosario: [
      { termino: "Φύρα", definicion: "Το ποσοστό πλακιδίων που αγοράζεται επιπλέον για κοψίματα και σπασμένα κομμάτια." },
      { termino: "Παρτίδα", definicion: "Σειρά παραγωγής. Η απόχρωση πλακιδίων από διαφορετικές παρτίδες μπορεί να διαφέρει λίγο." },
    ],
  };
};
