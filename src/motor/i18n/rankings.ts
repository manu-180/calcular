function ordinalEn(n: number): string {
  const regla = new Intl.PluralRules("en", { type: "ordinal" }).select(n);
  return `${n}${{ one: "st", two: "nd", few: "rd", other: "th" }[regla as "one" | "two" | "few" | "other"] ?? "th"}`;
}

