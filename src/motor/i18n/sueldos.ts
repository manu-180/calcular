// El nombre de la ocupación dentro de una frase: en minúscula donde el idioma lo pide (no en alemán,
// que escribe los sustantivos con mayúscula, ni en los idiomas sin mayúsculas).
export function ocupacionEnFrase(nombre: string, idioma: Idioma): string {
  if (idioma === "de" || idioma === "ja" || idioma === "ko" || idioma === "zh") return nombre;
  // Siglas al principio (IT, TI) quedan como están.
  if (/^\p{Lu}{2}/u.test(nombre)) return nombre;
  return nombre.charAt(0).toLocaleLowerCase(idioma) + nombre.slice(1);
}
